//     · 档 0 = 变调：⭐ 左推子（CH2）只管降、⭐ 右推子（CH3）只管升，⭐ 各占半程
//     · 档 1 = 颤音（现状）：CH2 = 颤音深度、CH3 = 颤音速率
//     · 档 2/3 = 预留摇把 ⇒ ⭐ 本版【不可达】（⛔ 不是"暂未实现"，是刻意不可达）
//     · ⭐ 上电默认档 1 ⇒ 与现状逐位一致 ⇒ 零回归
//
// ── 档位表（定稿 §四）────────────────────────────────────────────────────
//     档 | CH2（左推子）        | CH3（右推子）        | 状态
//     ---+-----------------------+-----------------------+----------
//      0 | 降调 0 → −12 半音     | 升调 0 → +12 半音     | 启用
//      1 | 颤音深度（现状）      | 颤音速率（现状）      | 启用（默认）

// ─────────────────────────────────────────────────────────────────────────────
// axis_map.v · W3a 语义层：轴位 → phase_inc
//
// ⭐ 冻结定义（`files/20-代码/代码总览图.md:195`）：
//    *"轴位 → `phase_inc`（两层表；滑音=双压插值）"*
//    ⭐ **传相位增量，⛔ 不传音名** —— ⚠️ **为了避开指数运算**：
//       ⚠️ 音名 → 频率 → 相位增量要算 `2^(n/12)`（**指数**）⇒ 大 LUT 或 DSP；
//       ⭐ 改成"**预先算好一张表、运行期只查表**" ⇒ ⭐ **零指数运算**。
//
// ⭐ 两层表（`产品形态决议清单.md` §2.4 / §七）：
//    | 层 | 输入 → 输出 | 说明 |
//    |---|---|---|
//    | **第 1 层** | `pos_i`(12bit 轴位) → `key_idx`（键位索引）| ⭐ 位置 → 键位 |
//    | **第 2 层** | `key_idx` → `phase_inc`(32bit) | ⭐ 键位 → 相位增量 |
//   ⭐ **双模式**：`mode_i` 选**哪一张第 2 层表**（键盘 / 指板）—— ⚠️ **结构相同、内容不同**。
//
// ── 🔴 本模块的【职责边界】（⛔ 改接口前先读）────────────────────────────────
//   ⭐ **本模块只做【机构】，⛔ 不管【表内容】**（2026-09-23 用户拍板）：
//     · 表内容（哪个轴对哪个音、音阶/调式、起始音）= ⚠️ **由映射表负责人填**
//     · 本模块提供**可换表**的接口 + **一张【示例表】**（⚠️ 仅为自检/变异体服务）
//   ⇒ ⭐ **换表 = 只改 `KEY_PITCH_*` 常量，⛔ 不动逻辑**。
//
// ── ⛔ 纪律 ───────────────────────────────────────────────────────────────────
//   · ⭐ **Verilog-2001**（`K-91`：⛔ 不用 SV 专有构造，否则整个模块被静默丢弃）
//   · ⭐ **同步复位、低有效**、⭐ **单时钟域 50 MHz**（冻结表 §〇 约定 1/2）
//   · ⭐ **`valid` 与数据必须同拍**（`K-109` / `U-18b ②`：⚠️ 本模块用**组合**输出保证同拍）
//   · ⛔ **输出 `phase_inc_o` 永不为 0**（⭐ `tick_inc=0` 会让音乐时钟静止，见总账 §5.1 风险 3）
// ─────────────────────────────────────────────────────────────────────────────
`default_nettype none

module axis_map #(
    // ⭐ 轴号位宽：4 = 最多 16 轴（⭐ `note_manager.AXIS_W` 现成值 ⇒ 零改动复用）
    parameter integer AXIS_W   = 4,
    // ⭐ 轴位（已标定）位宽：12bit = MCP3208 满量程
    parameter integer POS_W    = 12,
    // ⭐ 输出相位增量位宽（冻结表 §二：`PHASE_W = 32`）
    parameter integer PHASE_W  = 32,
    // ⭐ **每个轴分几段**（= 第 1 层表的分辨率）。
    //   ⚠️ 必须 ≥ 2（否则双压插值没有"相邻两键"可言）
    parameter integer N_KEY    = 16,
    // ⭐ **相邻键的相位增量比例**（Q16 定点，`2^(1/12)` ≈ 1.059463 ⇒ 1.059463 × 65536 ≈ 69433）
    //   ⭐ **半音比例**（⭐ 12 平均律）；⚠️ 换律制只改这个常数。
    parameter integer SEMITONE_Q16 = 69433,
    // ⭐ **基准相位增量**（= 键 0 的 `phase_inc`）。
    //   ⚠️ **示例值** `32'h0010_0000`（⭐ 约 122 Hz @ 48.828 kHz）——
    //      🔴 **真实值由映射表负责人填**（⛔ 本模块不规定音高）。
    parameter [PHASE_W-1:0] BASE_INC = 32'h0010_0000
) (
    input  wire                    clk,
    input  wire                    rst_n,        // ⭐ 同步复位、低有效

    // ── 输入：已标定轴位（⭐ 来自 `calib`）──────────────────────────────────
    input  wire                    pos_valid_i,  // ⭐ 与 pos_i/axis_id_i **同拍**
    input  wire [AXIS_W-1:0]       axis_id_i,    // ⭐ 轴号（= 片号×8 + 片内通道，见设计草案 §1.1）
    input  wire [POS_W-1:0]        pos_i,        // ⭐ 已标定轴位

    // ── 模式选择（第 2 层表二选一）─────────────────────────────────────────
    //   ⭐ `0` = 键盘模式（⭐ 见下 §KEYBOARD）· `1` = 指板模式（⚠️ 表内容待填）
    input  wire                    mode_i,

    // ── 输出：相位增量（⭐ **组合**输出 ⇒ 与 `phase_valid_o` 严格同拍）──────
    //   ⚠️ 为什么组合而不是寄存：⭐ 冻结表 §四 要求"事件通路低延迟且固定"，
    //      而 ⭐ **"valid 与 data 不同拍"是本项目已犯过的真缺陷**（`K-109` / `U-18b`）。
    //      ⇒ ⭐ **用组合输出从结构上消灭这一类缺陷**（⭐ 变异体 `M79` 就是守它的）。
    output wire [PHASE_W-1:0]      phase_inc_o,
    output wire                    phase_valid_o,
    output wire [AXIS_W-1:0]       axis_id_o
);

    // ═══════════════════════════════════════════════════════════════════════
    // ⭐ 第 1 层表：轴位 `pos_i` → 键位索引 `key_idx`（⚠️ 纯组合）
    //
    //   做法：把 `POS_W` 位量程**均分**成 `N_KEY` 段 ⇒ `key_idx = pos_i >> SHIFT`
    //   ⚠️ 要求 `N_KEY` 是 2 的幂（本模块用 `SHIFT` 实现，⛔ 不做除法）
    //      ⇒ ⭐ 参数自检会报 `N_KEY` 非 2 的幂（见文件末 `PARAM_OK`）
    // ═══════════════════════════════════════════════════════════════════════
    // 🔴🔴 **`SHIFT` 是【量程/N_KEY】的对数，⛔ 不是 `log2(N_KEY)`！**
    //   ⚠️ **踩过的坑（2026-09-23，本模块第三版 —— 最隐蔽的一个）**：
    //      🔴 我原来写 `SHIFT = $clog2(N_KEY)` = 4（按"16 个键 ⇒ 4 bit 索引"想当然）。
    //      ⚠️ **但那是"索引的位宽"，不是"位置量的右移数"** —— ⭐ 两者搞混了：
    //        · **段宽** = `2^POS_W / N_KEY` = `4096/16` = **256** ⇒ ⭐ **`SHIFT = log2(256) = 8`**
    //        · 而 `log2(N_KEY)=4` ⇒ 🔴 `pos=256` 得 `key_idx=16` **越过表顶**
    //          ⇒ ⭐ 被钳位成 15 ⇒ **整条量程只剩首尾两键**（实测 key_sel 恒 15）。
    //   ⭐ **正确关系**：`SHIFT = POS_W - log2(N_KEY)`（⚠️ 要求 `N_KEY` 是 2 的幂，自检已守）。
    //   📌 **教训**：⭐ **"索引位宽" ≠ "右移数"** —— 混用会**静默越界+钳位**，
    //      而 ⚠️ 钳位后的值**永远合法** ⇒ 🔴 判据不报警（⭐ 与上一个坑同族：**静默失效**）。
    localparam integer KW    = (N_KEY <= 1) ? 1 : $clog2(N_KEY);        // ⭐ 索引位宽
    localparam integer SHIFT = POS_W - KW;                              // ⭐ 右移数 = 量程/键数
    localparam integer FRAC_W = (SHIFT < 1) ? 1 : SHIFT;                // ⭐ 插值系数位宽

    // 🔴 **必须先把 `N_KEY` 落成【有宽度的向量】才能比较**（`K-91` 教训！）
    //   ⚠️ **踩过的坑（2026-09-23，本模块第一版）**：原来直接写 `N_KEY[KW-1:0]`
    //      ⇒ 🔴 **`N_KEY` 是 `integer`，Verilog-2001 ⛔ 不允许对 `integer` 参数做位选**
    //      ⇒ 实测 `N_KEY[3:0]` 求值为 **0**（⛔ 不是 16）⇒ ⭐ **钳位恒成立**
    //      ⇒ 🔴 **`key_sel` 永远 = `N_KEY-1`** ⇒ **整张表只剩最高键**（实测全输出同一值）。
    //   ⭐ 正确写法：先落成 `localparam` 向量（⭐ 与 `K-91` 修 `calib.sv` 时同一手法）。
    localparam [KW-1:0] N_KEY_V = N_KEY[KW-1:0];   // ⚠️ 此处的位选在 localparam 定宽后合法
    localparam [KW-1:0] KEY_MAX = N_KEY_V - 1'b1;

    // 🔴🔴 **`key_idx` 的位宽【必须够宽】，⛔ 不能声明成 `[KW-1:0]`**
    //   ⚠️ **踩过的坑（2026-09-23，本模块第二版 —— 比上面那个更隐蔽）**：
    //      ⭐ `pos_i[POS_W-1:SHIFT]` 是 **`POS_W-SHIFT` 位**（12-4 = **8 位**）。
    //      🔴 若把 `key_idx` 声明成 4 位 ⇒ **截断只留低 4 位** ⇒
    //      ⭐ 实测 `pos=256/512/768/1024/1280` 的 `[11:4]` = `16/32/48/64/80`
    //      ⇒ **低 4 位全是 0** ⇒ 🔴 **所有键边界都读成 key 0**（⚠️ 而 `pos<16` 时又"看着对"）。
    //   ⇒ ⭐ **正确做法：中间量用【全宽】`[POS_W-SHIFT-1:0]`，只在与 `KEY_MAX` 比较时比**。
    //   📌 **教训**：⭐ **切片表达式赋给窄向量 = 静默截断**；⚠️ 而截断后的值**仍在合法范围内**
    //      ⇒ ⛔ **钳位判据不会报警** ⇒ 🔴 **典型的静默失效**。

    // ⭐ 键位索引（**全宽**！⭐ 立即数右移 = 零延迟、零除法器）
    wire [POS_W-SHIFT-1:0] key_idx = pos_i[POS_W-1:SHIFT];

    // ⚠️ 上界钳位：`pos_i` 满量程时 `key_idx` 可能达 `N_KEY`（越界）⇒ ⭐ 钳到 `N_KEY-1`。
    //   ⚠️ 为什么必须有：⭐ 判据 2（"轴位满量程 → 表顶"）**就是守这条的**；
    //      若越界 ⇒ 读表拿到 X 或绕回表底 ⇒ ⭐ **顶键映射错**。
    //   🔴 **比较常量的位宽也要够**：⭐ 原来写 `[POS_W-SHIFT-1:0] N_KEY_FULL = N_KEY`
    //      ⇒ ⚠️ `SHIFT=8` 时该向量只有 **4 位** ⇒ 🔴 **`N_KEY=16` 截断成 0**
    //      ⇒ **钳位恒成立**（实测 `key_sel` 恒 15）⇒ ⭐ **又一类同族静默截断**。
    //   ⇒ ⭐ 用 **`integer` 直接比较**（⭐ 不做位选 ⇒ 无截断风险），⛔ 不落成窄向量。
    wire [KW-1:0] key_sel = (key_idx >= N_KEY) ? KEY_MAX : key_idx[KW-1:0];

    // ═══════════════════════════════════════════════════════════════════════
    // ⭐ 第 2 层表：`key_sel` → `phase_inc`
    //
    //   🔴 **表内容 = 映射表负责人的工作**（⛔ 本模块不规定音高）。
    //   ⭐ 本模块给出的是**机构**：`phase_inc(key) = BASE_INC × (SEMITONE_Q16/65536)^key`
    //      ⚠️ 但**运行期不做指数** —— ⭐ 改成**逐级乘 + 反复用同一个乘法器**太慢，
    //      ⇒ ⭐ 本示例用**查表**（`KEY_INC` 常量数组），⚠️ 换表只改数组。
    //
    //   ⚠️ 示例表 = **半音阶梯**（⭐ 仅为自检/变异体服务，⛔ 不是最终音高）：
    //      `KEY_INC[k] = BASE_INC × 2^(k/12)`
    // ═══════════════════════════════════════════════════════════════════════
    //   半音比例（Q16 定点）：2^(1/12) = 1.059463094 ⇒ × 65536 = 69432.6 ⇒ **69433**
    //   ⚠️ 表由 `function` 在**编译期**算（⭐ 综合器会折叠成常量 ⇒ ⛔ 无运行期开销）
    function [PHASE_W-1:0] key_inc;
        input integer k;
        integer i;
        reg [63:0] acc;      // ⭐ 64bit 中间量（⭐ 防溢出：32bit × 1.06 会丢精度）
        begin
            acc = BASE_INC;
            for (i = 0; i < k; i = i + 1)
                acc = (acc * SEMITONE_Q16) >> 16;
            key_inc = acc[PHASE_W-1:0];
        end
    endfunction

    // ⭐ **表生成：用 `initial` 在时刻 0 算好**（⛔ 不用 generate+function —— 见下方教训）
    //
    //   🔴 **踩过的坑（2026-09-23，本模块第一版）**：
    //      ⚠️ 我原来写 `generate for (gi...) assign tbl[gi] = func(gi);`
    //      ⇒ 🔴 **所有表项都得到同一个值**（实测 key0~3 全是 `0x00260dff`，而正确值应递增）。
    //      ⭐ **根因**：`function` 的参数在**连续赋值/genvar 上下文里求值不可靠** ——
    //        ⚠️ iverilog 把它当成"对同一表达式的多次引用"而非"逐实例求值"。
    //      ⇒ ⭐ **改成 `initial` 块里用循环填表**（⭐ 语义明确，且 ⭐ **仍被综合器折叠成常量 ROM**：
    //         `initial` 对 `reg` 数组赋常量 ⇒ 综合出 **常量表**，⛔ 无运行期逻辑）。
    //      📌 **教训**：⭐ **"编译期常量表"要写成 `initial` + 循环，⛔ 不要用 generate+function**。
    reg [PHASE_W-1:0] kb_inc [0:N_KEY-1];    // ⭐ 键盘模式表
    reg [PHASE_W-1:0] fb_inc [0:N_KEY-1];    // ⭐ 指板模式表

    // ⭐ 半音比例（Q16 定点）：2^(1/12) = 1.059463094 ⇒ × 65536 = 69432.6 ⇒ **69433**
    //
    //   🔴 **表内容 = 映射表负责人的工作**（⛔ 本模块不规定音高）。
    //      ⭐ 下面填的是**示例表 = 半音阶梯**（`BASE_INC × 2^(k/12)`），
    //      ⚠️ **仅为自检/变异体服务，⛔ 不是最终音高**。
    //   ⭐ **换表 = 只改下面两个任务的内容**（⛔ 不动任何选择逻辑）。
    //
    // ═══════════════════════════════════════════════════════════════════════
    // ⭐⭐ 指板模式表（`fb_inc`）—— **真实音高，2026-09-23 用户确认**
    //
    //   ⭐ 依据：`files/10-硬件/指板示意图.drawio.svg` + 用户口述
    //   ⭐ 布局（**两块板上下叠**）：
    //      | | 品1 | 品2 | 品3 | 品4 |
    //      |---|---|---|---|---|
    //      | **一弦**（右板 上排）| C4 | C#4 | D4 | D#4 |
    //      | **二弦**（右板 下排）| G3 | G#3 | A3 | A#3 |
    //      | **三弦**（左板 上排）| D3 | D#3 | E3 | F3 |
    //      | **四弦**（左板 下排）| A2 | A#2 | B2 | C3 |
    //   ⭐ **滑弦沿品方向**（同一排内 品1→品4）⇒ ⭐ **半音递增 = 等间距** ✅
    //
    //   🔴 **⚠️ 本模块输入是【单轴连续量】（每次一个 CH）** ⇒ ⭐ **"弦"由 `axis_id` 决定**：
    //      轴号 = `adc_idx × 8 + CH`（⭐ 见 `files/10-硬件/霍尔键位-CH映射-20260923.md`）
    //      ⚠️ **本模块【不知道】自己拿到的轴是哪条弦** ——
    //      ⇒ ⭐ **弦的选择由【调用方】用 `axis_id` 选表后传入**（⚠️ 见文件末 §集成说明）。
    //
    //   ⚠️ **当前实现（占位）**：本模块**只有一个 `pos_i` 输入**，
    //      ⇒ ⭐ **暂时用"位置"在一个 4 品表上插值** ⇒ ⚠️ **只能表达【一条弦】**。
    //      🔴 **真实的多弦选择需要第二层索引（轴号 → 弦/品）** ——
    //          ⚠️ **那属于"集成"阶段**（⭐ 设计草案 §三 的数据流）⇒ ⭐ 见下方 TODO。
    // ═══════════════════════════════════════════════════════════════════════

    //   ⭐ `phase_inc` 换算（⭐ 与 `top.v` 的 `INC_E5` 同一算式，已交叉验证）：
    //      `phase_inc = round(f_note / f_s × 2^32)`，`f_s = 50MHz/1024 = 48828.125 Hz`
    //      ⭐ 校验：`INC_E5 = 0x0374_D64B` ⇒ 反算 **659.25 Hz** = 标准 E5 ✅
    //
    // ═══════════════════════════════════════════════════════════════════════
    // ⭐⭐ **16 轴全表**（⭐ 2026-09-23 用户确认版）
    //
    //   ⭐ **轴号 = `adc_idx × 8 + CH`**（⭐ 依据 `霍尔键位-CH映射-20260923.md`）
    //      · 左板 `adc_idx=0`（轴 0~7）· 右板 `adc_idx=1`（轴 8~15）
    //      · 每板内：**上排 = `CH6 CH7 CH0 CH1`**（物理列 1~4）
    //                 **下排 = `CH5 CH4 CH3 CH2`**（物理列 1~4）
    //      ⇒ ⭐ **轴号【不按物理位置递增】** —— ⚠️ 这正是"必须用表、⛔ 不能用算术"的原因。
    //
    //   ⭐ 映射表（⭐ 轴号 → 音高）：
    //      | 轴 | 板 | 排 | CH | 弦 | 品 | 音 | `phase_inc` |
    //      |---|---|---|---|---|---|---|---|
    //      | 0 | 左 | 下 | 5 | 四 | 1 | `A2`  | `0x0093_A3B6` |
    //      | 1 | 左 | 下 | 4 | 四 | 2 | `A#2` | `0x009C_6B2A` |
    //      | 2 | 左 | 下 | 3 | 四 | 3 | `B2`  | `0x00A5_B841` |
    //      | 3 | 左 | 下 | 2 | 四 | 4 | `C3`  | `0x00AF_92EE` |
    //      | 4 | 左 | 上 | 6 | 三 | 1 | `D3`  | `0x00C5_1339` |
    //      | 5 | 左 | 上 | 7 | 三 | 2 | `D#3` | `0x00D0_CB35` |
    //      | 6 | 左 | 上 | 0 | 三 | 3 | `E3`  | `0x00DD_3595` |
    //      | 7 | 左 | 上 | 1 | 三 | 4 | `F3`  | `0x00EA_5CF4` |
    //      | 8 | 右 | 下 | 5 | 二 | 1 | `G3`  | `0x0107_104E` |
    //      | 9 | 右 | 下 | 4 | 二 | 2 | `G#3` | `0x0116_B4CE` |
    //      | 10 | 右 | 下 | 3 | 二 | 3 | `A3` | `0x0127_476D` |
    //      | 11 | 右 | 下 | 2 | 二 | 4 | `A#3` | `0x0138_D653` |
    //      | 12 | 右 | 上 | 6 | 一 | 1 | `C4`  | `0x015F_25DC` |
    //      | 13 | 右 | 上 | 7 | 一 | 2 | `C#4` | `0x0174_073A` |
    //      | 14 | 右 | 上 | 0 | 一 | 3 | `D4`  | `0x018A_2672` |
    //      | 15 | 右 | 上 | 1 | 一 | 4 | `D#4` | `0x01A1_966B` |
    //
    //   ⭐ **滑弦沿品方向**（同一排内 品1→品4）⇒ ⭐ **半音递增 = 等间距** ✅
    // ═══════════════════════════════════════════════════════════════════════
    //   四弦 A2 A#2 B2 C3
    localparam [PHASE_W-1:0] FB_AX0  = 32'h0093_A3B6;   // A2  (110.00 Hz)
    localparam [PHASE_W-1:0] FB_AX1  = 32'h009C_6B2A;   // A#2 (116.54 Hz)
    localparam [PHASE_W-1:0] FB_AX2  = 32'h00A5_B841;   // B2  (123.47 Hz)
    localparam [PHASE_W-1:0] FB_AX3  = 32'h00AF_92EE;   // C3  (130.81 Hz)
    //   三弦 D3 D#3 E3 F3
    localparam [PHASE_W-1:0] FB_AX4  = 32'h00C5_1339;   // D3  (146.83 Hz)
    localparam [PHASE_W-1:0] FB_AX5  = 32'h00D0_CB35;   // D#3 (155.56 Hz)
    localparam [PHASE_W-1:0] FB_AX6  = 32'h00DD_3595;   // E3  (164.81 Hz)
    localparam [PHASE_W-1:0] FB_AX7  = 32'h00EA_5CF4;   // F3  (174.61 Hz)
    //   二弦 G3 G#3 A3 A#3
    localparam [PHASE_W-1:0] FB_AX8  = 32'h0107_104E;   // G3  (196.00 Hz)
    localparam [PHASE_W-1:0] FB_AX9  = 32'h0116_B4CE;   // G#3 (207.65 Hz)
    localparam [PHASE_W-1:0] FB_AX10 = 32'h0127_476D;   // A3  (220.00 Hz)
    localparam [PHASE_W-1:0] FB_AX11 = 32'h0138_D653;   // A#3 (233.08 Hz)
    //   一弦 C4 C#4 D4 D#4
    localparam [PHASE_W-1:0] FB_AX12 = 32'h015F_25DC;   // C4  (261.63 Hz)
    localparam [PHASE_W-1:0] FB_AX13 = 32'h0174_073A;   // C#4 (277.18 Hz)
    localparam [PHASE_W-1:0] FB_AX14 = 32'h018A_2672;   // D4  (293.66 Hz)
    localparam [PHASE_W-1:0] FB_AX15 = 32'h01A1_966B;   // D#4 (311.13 Hz)

    integer ti;
    initial begin
        // ── ⭐ 键盘模式（`kb_inc`）= 半音阶梯（⚠️ **示例，待填**）──────────────
        //   🔴 **TODO**：⭐ 钢琴模式的真实音高表（`C D E F G A B` + 上排升号）**尚未填**
        for (ti = 0; ti < N_KEY; ti = ti + 1)
            kb_inc[ti] = key_inc(ti);

        // ── ⭐⭐ 指板模式（`fb_inc`）= **16 轴全表**（⭐ 真实音高）──────────────
        //   ⭐ 索引 = **轴号**（`adc_idx × 8 + CH`）⇒ ⭐ 由调用方用 `axis_id_i` 直接选
        //   ⚠️ 但本模块**只有一个 `pos_i` 输入**（一次一个轴）
        //      ⇒ ⭐ **真正的"按轴选音"需要【16 轴快照】upside（⭐ 见设计草案 §三 / TODO）**
        fb_inc[0]  = FB_AX0;
        fb_inc[1]  = FB_AX1;
        fb_inc[2]  = FB_AX2;
        fb_inc[3]  = FB_AX3;
        fb_inc[4]  = FB_AX4;
        fb_inc[5]  = FB_AX5;
        fb_inc[6]  = FB_AX6;
        fb_inc[7]  = FB_AX7;
        fb_inc[8]  = FB_AX8;
        fb_inc[9]  = FB_AX9;
        fb_inc[10] = FB_AX10;
        fb_inc[11] = FB_AX11;
        fb_inc[12] = FB_AX12;
        fb_inc[13] = FB_AX13;
        fb_inc[14] = FB_AX14;
        fb_inc[15] = FB_AX15;
    end

    // ═══════════════════════════════════════════════════════════════════════
    // ⭐⭐ 双压插值（滑音的核心）
    //
    //   ⭐ 冻结定义：*"滑音=相邻双压插值"*（`代码总览图.md:195`）
    //   ⭐ 语义：两个相邻键同时按下 ⇒ 输出**在两者之间插值**（⛔ 不是任一端点）
    //   ⚠️ 本模块的输入是**单轴连续量** ⇒ "双压"体现为**轴位落在两键边界之间**：
    //      · `pos_i` 的低 `SHIFT` 位 = 段内偏移 ⇒ ⭐ 天然就是插值系数 `frac`
    //      · `frac = 0` ⇒ 取低键；`frac = 满` ⇒ 取高键；中间 ⇒ ⭐ **线性插值**
    //   ⇒ ⭐ **本模块用【同一个乘法器】算插值**（⚠️ 不用除法器 ⇒ 延迟确定、资源省）
    // ═══════════════════════════════════════════════════════════════════════
    //   ⭐ 段内偏移 = `pos_i` 的低 `SHIFT` 位（⭐ 天然就是插值系数 `frac`）
    wire [FRAC_W-1:0] frac = pos_i[SHIFT-1:0];

    // ⭐ 相邻两键的相位增量
    wire [PHASE_W-1:0] inc_lo = mode_i ? fb_inc[key_sel] : kb_inc[key_sel];
    // ⚠️ 高键 = 低键 +1，**必须钳位**（⛔ 否则顶键越界）
    //   🔴 同上方教训：⛔ **用定宽向量 `KEY_MAX` 比较**，⛔ 不要写 `N_KEY[KW-1:0]`
    wire [KW-1:0]      hi_sel = (key_sel >= KEY_MAX) ? KEY_MAX : (key_sel + 1'b1);
    wire [PHASE_W-1:0] inc_hi = mode_i ? fb_inc[hi_sel] : kb_inc[hi_sel];

    // ⭐ 线性插值：`out = lo + (hi - lo) × frac / 2^SHIFT`
    //   ⚠️ 用**移位代替除法**（⭐ `frac` 只有 `SHIFT` 位 ⇒ 除以 `2^SHIFT`）
    wire [PHASE_W-1:0] inc_delta = inc_hi - inc_lo;
    wire [PHASE_W+FRAC_W-1:0] interp_raw = inc_delta * frac;    // ⚠️ 位宽必须够（PHASE_W + FRAC_W）
    wire [PHASE_W-1:0] interp = (SHIFT < 1) ? {PHASE_W{1'b0}}
                                             : interp_raw[PHASE_W+FRAC_W-1:SHIFT];

    // ⭐ **结果**：低键 + 插值增量
    wire [PHASE_W-1:0] phase_calc = inc_lo + interp;

    // ⭐⭐ **保护：`phase_inc_o` ⛔ 永不为 0**
    //   🔴 依据：⭐ `tick_inc = 0` ⇒ 音乐时钟**静止**（总账 §5.1 风险 3）。
    //   ⚠️ 正常情况 `BASE_INC ≥ 1` 已保证；⭐ 这里再加一道**结构性护栏**，
    //      因为 ⚠️ **换表时若误填 `BASE_INC = 0`，整条链路会静默静止**。
    wire [PHASE_W-1:0] phase_safe = (phase_calc == {PHASE_W{1'b0}}) ? {{(PHASE_W-1){1'b0}}, 1'b1}
                                                                    : phase_calc;

    // ── 输出（⭐ 组合 ⇒ 与 `axis_id_o` 严格同拍）─────────────────────────────
    assign phase_inc_o   = phase_safe;
    assign phase_valid_o = pos_valid_i;      // ⭐ 直通 ⇒ 与数据同拍（⭐ 判据 4）
    assign axis_id_o     = axis_id_i;        // ⭐ 透传（下游按轴寻址）

    // ═══════════════════════════════════════════════════════════════════════
    // ⭐ 参数自检（与 `clk_gen`/`tlc5916`/`top` 的 `PARAM_OK` 同一套路）
    //   ⚠️ 为什么要有：⭐ 这些参数的**错误组合会静默失效**，且**现象极难定位**：
    //     ① `N_KEY` **非 2 的幂** ⇒ `SHIFT` 丢低位 ⇒ ⚠️ **整张表错位**（⭐ 不报错）
    //     ② `N_KEY < 2` ⇒ ⚠️ **没有"相邻两键"** ⇒ 双压插值**结构上无意义**
    //     ③ `BASE_INC = 0` ⇒ ⚠️ 输出恒 0 ⇒ **音乐时钟静止**（⭐ 已由 `phase_safe` 兜底，
    //        但**自检要报**，因为这说明表填错了）
    //     ④ `FRAC_W < 1` ⇒ 插值系数恒 0 ⇒ ⚠️ **滑音退化成"只认低键"**（⭐ 判据 3 的守护）
    // ═══════════════════════════════════════════════════════════════════════
    localparam NKEY_IS_POW2 = ((N_KEY & (N_KEY - 1)) == 0);
    localparam PARAM_OK     = (N_KEY >= 2) && NKEY_IS_POW2 && (BASE_INC != 0);

    initial begin
        if (BASE_INC == {PHASE_W{1'b0}})
            $display("ERROR [axis_map] BASE_INC = 0 => phase_inc would be 0 and the musical clock would FREEZE. Fill in the real pitch table (PARAM_OK=0).");
        if (N_KEY < 2)
            $display("ERROR [axis_map] N_KEY = %0d < 2 => there is no adjacent-key pair, so dual-press interpolation is meaningless (PARAM_OK=0).", N_KEY);
        if (!NKEY_IS_POW2)
            $display("ERROR [axis_map] N_KEY = %0d is not a power of two => the >>SHIFT index loses low bits and the whole table is misaligned (PARAM_OK=0).", N_KEY);
        if (PARAM_OK)
            $display("NOTE [axis_map] PARAM_OK=1 (AXIS_W=%0d POS_W=%0d PHASE_W=%0d N_KEY=%0d SHIFT=%0d FRAC_W=%0d)",
                     AXIS_W, POS_W, PHASE_W, N_KEY, SHIFT, FRAC_W);
    end

endmodule


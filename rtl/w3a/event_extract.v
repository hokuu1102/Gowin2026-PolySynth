            //      ⇒ ⭐ 需要一张【邻居表】（⭐ 见 `霍尔键位-CH映射-20260923.md`）
            // ═══════════════════════════════════════════════════════════════
            // ⭐⭐⭐⭐ 2026-10-11：⭐ **滑音判据已实现**（⭐ 见 `review/滑音触发规格-20261011.md` ✅）
            //

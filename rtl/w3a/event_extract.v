            //  ⚠️ 本行必须是本块中 `q_cnt` 的**唯一**赋值。
            //  ═══════════════════════════════════════════════════════════════
            q_cnt <= q_cnt + (q_push_now ? 1'b1 : 1'b0)
                           - ((q_cnt != 0) ? 1'b1 : 1'b0);


`timescale 1ns/1ps
// ─────────────────────────────────────────────────────────────────────────────
// rst_sync.v · **复位同步器**（R-08，2026-09-17 加）
//
// ⭐ 为什么需要它：本设计统一用**同步复位**（`W3接口冻结表.md` §〇 约定 2），
//    但 `rst_n` 来自**板上的按键/引脚**，是**异步输入**。直接把它当同步复位分发到所有 FF，
//    会有一个真实风险：
//      · 按键抖动或释放沿**恰好落在某个 FF 的 setup/hold 窗内** ⇒ 不同 FF 采到**不同值**
//        （一部分复位了、一部分没复位），而且各模块可能**互相不一致**；
//      · 全设计都是 `if (!rst_n)` ⇒ 这个不一致会一直保留到下一次复位。
//    ⇒ 标准做法是「**异步置位 / 同步释放**」：复位**立刻**生效（异步），
//      **释放**经过两级 FF 同步（同步）—— 这样释放沿在全设计里是**同一个时钟沿**。
//
// ⚠️ 本模块刻意**不**把 `rst_n` 接进第一级 FF 的异步复位端（那需要异步复位端口，
//    与"全设计同步复位"的约定不符，且 Gowin 上还要额外处理 recovery/removal）。
//    这里的做法是**纯同步**的：`rst_n` 先被两级 FF 采样，再作为"同步复位"分发。
//    代价：复位**生效**晚 2 拍（⛔ 对本设计无影响：音频/灯的复位延迟 40 ns 完全无所谓），
//    收益：**释放沿在全设计里严格对齐**，且亚稳态被隔离在第一级之后。
//
// ⚠️ 注意 `rst_n` 是**低有效**：`rst_n_sync` 也是低有效。
//
// ⚠️ 已知限制（⛔ 不要误解为"已经完全解决"）：
//    ① 它隔离的是**亚稳态**，**不**去抖按键的机械抖动（那是 `debounce` 的事，`T14`）；
//    ② 若 `rst_n` 上的毛刺短于 2 拍，会被它过滤掉（这正是我们要的）；
//       但**长于 2 拍**的毛刺仍会触发一次复位 —— 这是设计意图（复位本来就该生效）。
// ─────────────────────────────────────────────────────────────────────────────
module rst_sync #(
    parameter integer STAGES = 2          // 同步级数（≥2；默认 2）
) (
    input  wire clk,
    input  wire rst_n_async,              // 异步输入（板上来）
    output wire rst_n_sync                // 同步后的复位（低有效），分发给全设计
);

    // ⚠️ `(* async_reg = "true" *)` 是给综合器的提示（Gowin 会忽略未知属性，无害），
    //    目的是告诉工具"这两级不要被优化/重排"。
    (* async_reg = "true" *) reg [STAGES-1:0] sync_chain;

    always @(posedge clk) begin
        // ⚠️ 这里**故意不用 `if (!rst_n_sync)`**：本模块自己就是复位的源头，
        //    用输入直接灌链即可（否则就成了自复位）。
        sync_chain <= {sync_chain[STAGES-2:0], rst_n_async};
    end

    assign rst_n_sync = sync_chain[STAGES-1];

    // 上电时链是 X ⇒ 强制从"复位有效(0)"开始，避免上电瞬间放出不确定值。
    // ⭐ 这是本模块唯一使用 `initial` 的地方，且**只影响仿真**；
    //    真实硅片上 FF 上电为 0（Gowin 支持寄存器初始值）或由外部上拉保证 —— 
    //    ⚠️ 关键安全态（如功放使能）仍然靠 `.cst` 的 `PULL_MODE=UP`（见 `K-42`），⛔ 不靠这里。
    initial sync_chain = {STAGES{1'b0}};

endmodule

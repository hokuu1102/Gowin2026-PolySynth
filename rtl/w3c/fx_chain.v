`timescale 1ns/1ps
// ============================================================================
// fx_chain.v -- 效果器链（5 级串联）· W3c 出声通路
//
//  位置：tdm_render_mixer（干声）→ **fx_chain** → master_mix → i2s_tx
//
// ---------------------------------------------------------------------------
// 链的顺序（用户 2026-10-14 裁定，与真实效果器链一致）
// ---------------------------------------------------------------------------
//  dry ─►[失真]─►[合唱]─►[延迟]─►[混响·留位]─►[音量颤音]─► out
//         bit0     bit1     bit2      bit3        常开
//
//  为什么这个顺序：真实效果器链是 drive → modulation → time-based → 后级。
//  失真先塑造谐波，调制再加动感，时间类铺空间，音量颤音在后级调制整个信号
//  （含回声）。
//
// ---------------------------------------------------------------------------
// ⚠️ 延迟与合唱【各有自己的一条延迟线】—— 2026-10-15 用户要求"能同时开"
// ---------------------------------------------------------------------------
//  预研文档的原始设想是"一条缓冲 + 多个抽头"。但那条路有个**拓扑问题**：
//  共用一条线 ⇒ 两个效果实际是【并联】（都读同一份缓冲内容）
//  ⇒ 🔴 **串联顺序就丢了**（延迟回声里不会带着合唱）。
//
//  ✅ 改成【两条独立的线】，串联顺序正确：失真 → 合唱 → 延迟 → …
//     · 合唱线只要 **2048 样点（AW_CH=11）** ⇒ 42 ms 足够
//       （合唱的调制抽头典型 10~30 ms，深度 ±2.6 ms）
//     · 延迟线 16384 样点（AW=14）⇒ 335 ms
//     ⇒ 理想存储预算 18 块（2+16）；BJ 基线已是 83 块，不能再按旧69块相加。
//        具体物理块数及完整工程是否放得下必须重新综合、布局布线核验。
//
//  📌 若将来嫌 BSRAM 紧：可以退回"共用一条线 + 两个抽头"（省 2 块），
//     但**要接受并联拓扑**（延迟回声里不带合唱）⚠️
//
// ---------------------------------------------------------------------------
// ⚠️ 混响级是【留位直通】
// ---------------------------------------------------------------------------
//  用户裁定混响暂不做。所以 bit3 **当前无逻辑**，链上是直通（不花任何资源）。
//  留位 = 只留这个掩码位与这条注释，⛔ 不实例化任何东西。
//  将来要做：优先做"简易 2 梳"（共用现有延迟线的短抽头 ⇒ 零额外 BSRAM）。
//
// ---------------------------------------------------------------------------
// 零回归保证（这是敢做的底气）
// ---------------------------------------------------------------------------
//  · 失真 / 合唱 / 延迟三级：`out = en ? effect(in) : in`
//  · 音量颤音级：**常开**，但 `depth = 0` 时 `g = 256` ⇒ `(x×256)>>8 = x`
//    ⇒ 也是**逐位等于输入** ✓
//  ⇒ ⭐ **掩码 = 0（且颤音深度 = 0）⇒ 输出与今天的通路【数值逐位相同】** ✓
//  ⚠️ 如实说明：旁路走的是【同一条流水线】，所以数值相同但时序差
//     实测 17 拍（5+3+3+3 拍模块延迟 + 3 拍级间接收）= 340 ns @50 MHz。
//     相对本项目 10 ms 的延迟预算可忽略 ✓
//
// ---------------------------------------------------------------------------
// ⭐ 链的"第 0 级"：音高颤音（⛔ 不在本模块里，也不需要）
// ---------------------------------------------------------------------------
//  用户 2026-10-15 问："音高颤音能接在最前级吗？"
//  ✅ **能，而且它本来就在最前级** —— 只是位置在**振荡器域**，不在音频域：
//
//      音高颤音 ─► 振荡器 ─► … ─► tdm_render_mixer ─► [本模块] ─► master_mix
//      （第 0 级，改相位增量）                          （音频域 4 级）
//
//  🔴 **为什么不能搬进本模块**：本模块处理的是**已经生成的样点**。
//     要让音高在音频域变化，只能做**调制延迟线**（100% 湿、无干声）
//     ⇒ 那是**移调器**，要再花一条延迟线，而且线性插值会有音质损失，
//       听感**还不如现在**（现在改的是相位增量 = 真正的音高颤音）✗
//
//  📌 两者作用范围不同（这是真实设备上的分工，不是妥协）：
//     · 音高颤音（振荡器域）：只作用于**新生成的音** ⇒ 不含 looper 回放
//     · 音量颤音（音频域，本模块最后一级）：作用于**全部输出** ⇒ 含回声
//
// ---------------------------------------------------------------------------
// 流水线（公开输入接收到公开输出有效：17 拍）
// ---------------------------------------------------------------------------
//  | 级 | 拍数 | 依据 |
//  |----|------|------|
//  | 失真   | 5 | `fx_dist.v` 的 PIPE |
//  | 合唱   | 3 | `fx_delay.v` 公开接受边沿 N 到输出边沿 N+3 |
//  | 延迟   | 3 | 同上（各自独立的实例） |
//  | 混响   | 0 | 留位直通 |
//  | 音量颤音 | 3 | `fx_trem.v` 的 PIPE |
//  | 级间接收 | 3 | 四个寄存模块之间的三次接收，总和17拍 |
//  ⚠️ `valid_i` 的脉冲间距必须满足各单级声明的要求（保守采用 ≥5拍）。
//     真实链路每 1024 拍一个样点，够。
//
// ---------------------------------------------------------------------------
// 纪律
// ---------------------------------------------------------------------------
//  · Verilog-2001 语法（K-91）；声明先于使用。
//  · 单样本链不反压：valid 逐级透传，`valid_o` 与 `sample_o` 同拍。
//  · 可观测（K-106）：生效掩码 / 延迟级实际模式 / 失真削波次数 —— 全部有输出。
// ============================================================================
`default_nettype none

module fx_chain #(
    parameter integer SAMPLE_W = 24,
    // ── 延迟/合唱（透传给 fx_delay）────────────────────────────────────
    //   ⭐ 2026-10-15：延迟与合唱【各有自己的一条线】
    //      · AW    = 14 ⇒ 16384 样点 ⇒ 335 ms ⇒ 16 块 BSRAM
    //      · AW_CH = 11 ⇒  2048 样点 ⇒  42 ms ⇒  2 块 BSRAM
    //      ⚠️ 两者都必须 >= 8（`fx_delay.v:169` 的 `TAP_W-18` 会变负）
    parameter integer AW       = 14,
    parameter integer AW_CH    = 11,
    parameter integer MIX_W    = 8,
    parameter integer FB_W     = 8,
    // ── 失真（透传给 fx_dist）──────────────────────────────────────────
    parameter integer GAIN_W   = 16,
    parameter integer TRIM_W   = 16,
    // ── 音量颤音（透传给 fx_trem）──────────────────────────────────────
    parameter integer DEPTH_W  = 8,
    parameter integer RATE_W   = 8,
    parameter integer LFO_W    = 16,
    //  兼容已有调用者的诊断总线位宽；不通过本参数改变实际流水。
    //  实际公开端口延迟为 17 拍，pipe_o 报告真实值，端口位宽保持不变。
    parameter integer PIPE_TOTAL = 16
) (
    input  wire                        clk_i,
    input  wire                        rst_n_i,     // 同步复位、低有效

    // ── 单样本流（与 master_mix 同一约定：valid_i 是脉冲，不反压）────────
    input  wire                        valid_i,
    input  wire signed [SAMPLE_W-1:0]  sample_i,

    // ── ⭐ 效果器链掩码（来自 uart_ui / 串口屏；本模块不解析串口）────────
    //    bit0 = 失真 · bit1 = 合唱 · bit2 = 延迟 · bit3 = 混响(留位) ·
    //    bit4 = 空闲（⭐ 原来给音量颤音，2026-10-15 改成常开后释放）· bit5..7 = 预留
    //  ⚠️ **音量颤音没有使能位** —— 它固定常开，靠深度推子置零（见下方 ⑥ 级）
    input  wire [7:0]                  en_mask_i,

    // ── 失真参数 ──────────────────────────────────────────────────────────
    input  wire [1:0]                  dist_sel_i,   // 0=硬削 · 1/2/3=预留
    input  wire [GAIN_W-1:0]           dist_gain_i,  // Q4.12
    input  wire [TRIM_W-1:0]           dist_trim_i,  // Q1.15

    // ── 延迟/合唱参数 ─────────────────────────────────────────────────────
    input  wire [AW-1:0]               dly_delay_i,  // 延迟时间（样点数）
    input  wire [AW_CH-1:0]            chor_delay_i, // ⭐ 合唱基础延迟（样点数，典型 732 = 15 ms）
    input  wire [MIX_W-1:0]            dly_mix_i,    // 干湿比（两级共用）
    input  wire [FB_W-1:0]             dly_fb_i,     // 反馈量（两级共用）

    // ── 音量颤音参数 ──────────────────────────────────────────────────────
    input  wire [DEPTH_W-1:0]          trem_depth_i, // Q0.8
    input  wire [RATE_W-1:0]           trem_rate_i,  // 每样点相位增量

    // ── 输出 ──────────────────────────────────────────────────────────────
    output wire                        valid_o,
    output wire signed [SAMPLE_W-1:0]  sample_o,

    // ── 可观测性（K-106：不许静默失效）────────────────────────────────────
    output wire [7:0]                  en_mask_o,      // 当前生效的掩码
    output wire                        dly_active_o,   // 延迟级是否在跑
    output wire                        chor_active_o,  // 合唱级是否在跑（可独立于延迟）
    output wire                        dly_primed_o,   // 延迟线已填满一圈
    output wire [15:0]                 dist_clip_cnt_o,// 失真削波次数
    output wire [LFO_W-1:0]            trem_lfo_o,     // 颤音 LFO 相位
    output wire [PIPE_TOTAL-1:0]       pipe_o          // 常数（拍数，供核对）
);

    assign en_mask_o = en_mask_i;
    localparam [PIPE_TOTAL-1:0] PIPE_CYCLES = 17;
    assign pipe_o    = PIPE_CYCLES;

    // ═══════════════════════════════════════════════════════════════════════
    // ① 各级的 enable / 模式（组合，从掩码解出来）
    // ═══════════════════════════════════════════════════════════════════════
    wire en_dist  = en_mask_i[0];
    wire en_chor  = en_mask_i[1];
    wire en_delay = en_mask_i[2];
    //  bit3 = 混响：留位，⛔ 无逻辑（链上直通）
    //  ⭐⭐ bit4（音量颤音）**不再是使能位** —— 用户 2026-10-15 裁定"固定常开" ✅
    //     理由：深度 = 0 时它【逐位等于输入】（`g = 256` ⇒ `(x×256)>>8 = x`）
    //     ⇒ 推子推到零就等于关掉，**不需要一个开关** ✓
    //     ⭐ 好处：省掉那个 24 位 2:1 旁路 mux（约 24 LUT）✓
    //     ⚠️ bit4 现在**空闲**（保留，将来可给别的效果）✓
    //     📌 颤音级的 `en_i` 在下面【硬接 1'b1】，不再从掩码取

    //  ⭐⭐ 2026-10-15：⭐ **延迟与合唱各自独立**（用户要求"能同时开"）✅
    //     · 合唱走自己的短延迟线（`u_chorus`，AW_CH=11）
    //     · 延迟走自己的长延迟线（`u_delay`，AW=14）
    //     · 两者**串联**（合唱在前）⇒ 延迟回声里带着合唱 ✓
    //     `fx_delay.sel_i` 的语义：0 = 延迟 · 1 = 合唱
    wire dly_active  = en_delay;
    wire chor_active = en_chor;

    assign dly_active_o  = dly_active;
    assign chor_active_o = chor_active;

    // ═══════════════════════════════════════════════════════════════════════
    // ② 第 1 级：失真
    // ═══════════════════════════════════════════════════════════════════════
    wire                       d1_valid;
    wire signed [SAMPLE_W-1:0] d1_sample;
    wire [15:0]                d1_clip;
    wire [GAIN_W-1:0]          d1_gain_used;
    wire [TRIM_W-1:0]          d1_trim_used;
    wire [SAMPLE_W-1:0]        d1_peak;

    assign dist_clip_cnt_o = d1_clip;

    fx_dist #(
        .SAMPLE_W (SAMPLE_W),
        .GAIN_W   (GAIN_W),
        .TRIM_W   (TRIM_W)
    ) u_dist (
        .clk_i(clk_i), .rst_n_i(rst_n_i),
        .valid_i(valid_i), .sample_i(sample_i),
        .en_i(en_dist), .sel_i(dist_sel_i),
        .gain_i(dist_gain_i), .trim_i(dist_trim_i),
        .valid_o(d1_valid), .sample_o(d1_sample),
        .clip_cnt_o(d1_clip), .gain_used_o(d1_gain_used),
        .trim_used_o(d1_trim_used), .peak_o(d1_peak)
    );

    // ═══════════════════════════════════════════════════════════════════════
    // ③ 第 2 级：合唱（自己的短延迟线 = 2048 样点 ≈ 2 块 BSRAM）
    //    ⭐ 为什么给它单独的线而不是共用：见文件头的拓扑说明 ✅
    // ═══════════════════════════════════════════════════════════════════════
    wire                       d2_valid;
    wire signed [SAMPLE_W-1:0] d2_sample;
    wire [AW_CH-1:0]           d2_wr_ptr;
    wire                       d2_primed;
    wire [15:0]                d2_sat_cnt;
    wire [15:0]                d2_clamp_cnt;

    fx_delay #(
        .SAMPLE_W (SAMPLE_W),
        .AW       (AW_CH),
        .MIX_W    (MIX_W),
        .FB_W     (FB_W)
    ) u_chorus (
        .clk_i(clk_i), .rst_n_i(rst_n_i),
        .valid_i(d1_valid), .sample_i(d1_sample),
        .en_i(chor_active), .sel_i(2'd1),        // sel=1 ⇒ 合唱（调制读地址）
        .delay_i(chor_delay_i), .mix_i(dly_mix_i), .fb_i(dly_fb_i),
        .valid_o(d2_valid), .sample_o(d2_sample),
        .wr_ptr_o(d2_wr_ptr), .primed_o(d2_primed),
        .sat_cnt_o(d2_sat_cnt), .clamp_cnt_o(d2_clamp_cnt)
    );

    // ═══════════════════════════════════════════════════════════════════════
    // ④ 第 3 级：延迟（自己的长延迟线 = 16384 样点 ≈ 16 块 BSRAM）
    //    ⭐ 输入是【合唱的输出】⇒ 串联顺序正确（回声里带着合唱）✅
    // ═══════════════════════════════════════════════════════════════════════
    wire                       d3_valid;
    wire signed [SAMPLE_W-1:0] d3_sample;
    wire [AW-1:0]              d3_wr_ptr;
    wire                       d3_primed;
    wire [15:0]                d3_sat_cnt;
    wire [15:0]                d3_clamp_cnt;

    assign dly_primed_o = d3_primed;

    fx_delay #(
        .SAMPLE_W (SAMPLE_W),
        .AW       (AW),
        .MIX_W    (MIX_W),
        .FB_W     (FB_W)
    ) u_delay (
        .clk_i(clk_i), .rst_n_i(rst_n_i),
        .valid_i(d2_valid), .sample_i(d2_sample),
        .en_i(dly_active), .sel_i(2'd0),         // sel=0 ⇒ 延迟（固定读地址）
        .delay_i(dly_delay_i), .mix_i(dly_mix_i), .fb_i(dly_fb_i),
        .valid_o(d3_valid), .sample_o(d3_sample),
        .wr_ptr_o(d3_wr_ptr), .primed_o(d3_primed),
        .sat_cnt_o(d3_sat_cnt), .clamp_cnt_o(d3_clamp_cnt)
    );

    // ═══════════════════════════════════════════════════════════════════════
    // ⑤ 第 4 级：混响 —— 【留位直通】（用户裁定暂不做）
    //    ⚠️ 这一级【没有逻辑】，只是一个命名清晰的接续点。
    //       将来要做：优先做"简易 2 梳"（复用 u_delay 那条线的短抽头 ⇒
    //       零额外 BSRAM）。届时把 d4_* 换成混响级的输出即可。
    //    📌 2026-10-15：本级的输入现在是【延迟级的输出】(d3_*)，不是合唱的
    //       —— 因为合唱与延迟已经拆成两级各自独立的线 ✅
    // ═══════════════════════════════════════════════════════════════════════
    wire                       d4_valid = d3_valid;
    wire signed [SAMPLE_W-1:0] d4_sample = d3_sample;

    // ═══════════════════════════════════════════════════════════════════════
    // ⑥ 第 5 级：音量颤音（放在最后 ⇒ 调制整个信号，含回声）
    //    ⭐⭐ 2026-10-15：**固定常开**（用户裁定）—— ⛔ 没有使能位 ✅
    //       理由：`depth = 0` 时 `g = 256` ⇒ `(x×256)>>8 = x` ⇒ **逐位等于输入**
    //       ⇒ 推子推到零就等于关掉，不需要开关 ✓
    //       ⭐ 好处：省掉 24 位 2:1 旁路 mux（约 24 LUT）✓
    //    📌 `fx_trem.v` 的 `en_i` 端口**保留**（模块本身还支持旁路，
    //       它自己的判据也测了旁路逐位相同）—— 只是**链里硬接常开** ✓
    // ═══════════════════════════════════════════════════════════════════════
    wire              d5_valid;
    wire signed [SAMPLE_W-1:0] d5_sample;
    wire [LFO_W-1:0]  d5_lfo;
    wire [7:0]        d5_tri;
    wire [DEPTH_W:0]  d5_gain;
    wire [DEPTH_W-1:0] d5_depth_used;
    wire [RATE_W-1:0]  d5_rate_used;

    assign trem_lfo_o = d5_lfo;

    fx_trem #(
        .SAMPLE_W (SAMPLE_W),
        .LFO_W    (LFO_W),
        .DEPTH_W  (DEPTH_W),
        .RATE_W   (RATE_W)
    ) u_trem (
        .clk_i(clk_i), .rst_n_i(rst_n_i),
        .valid_i(d4_valid), .sample_i(d4_sample),
        .en_i(1'b1), .depth_i(trem_depth_i), .rate_i(trem_rate_i),   // ⭐ 常开
        .valid_o(d5_valid), .sample_o(d5_sample),
        .lfo_o(d5_lfo), .tri_o(d5_tri), .gain_o(d5_gain),
        .depth_used_o(d5_depth_used), .rate_used_o(d5_rate_used)
    );

    // ═══════════════════════════════════════════════════════════════════════
    // ⑥ 输出（逐级透传，⛔ 不反压）
    // ═══════════════════════════════════════════════════════════════════════
    assign valid_o  = d5_valid;
    assign sample_o = d5_sample;

endmodule

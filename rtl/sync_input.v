`timescale 1ns/1ps
// ─────────────────────────────────────────────────────────────────────────────
// sync_input.v · **外部异步输入同步器**（2 级 FF，`K-62`）
//
// ⭐ 为什么需要它（2026-09-17 用户提问引出的真问题）：
//    `SCLK`/`MOSI`/`MISO`/`CS` 与**按键/开关**都是**板外来**的异步信号。
//    直接把异步信号接进状态机/比较器有两个经典风险：
//      ① **亚稳态**：信号在 FF 的 setup/hold 窗内跳变 ⇒ FF 输出可能停在中间电平，
//         并在**不确定的时间**才稳定 ⇒ 下游可能采到不同值（同一个信号被两个 FF 采成两个值）；
//      ② **多比特偏斜**：多根线（如 3 路 `MISO`）**各自**同步，若在跳变沿附近采样，
//         可能出现"这一拍读到的是 A 的旧值 + B 的新值"这种**不可能的组合**。
//
// ⭐⭐ 关于"FPGA 的上拉比较慢"（用户的疑问）—— **这个担心是对的，但结论要分清**：
//    · FPGA 内部上拉是**弱上拉**（典型 **10 kΩ ~ 50 kΩ** 量级），它只能保证
//      "**悬空时不会乱飘**"，**不能**当作"快速把线拉高"的手段：
//      对 ~10 pF 的线，10 kΩ 的上升时间约 `τ=RC≈100 ns`（到 90% 约 230 ns）——
//      ⚠️ **远慢于**我们 1 MHz SPI 的 500 ns 半周期，**在临界上**。
//    · ⇒ 结论 ①：⭐ **SPI 的 `MISO` 不要依赖 FPGA 内部上拉来做"电平拉高"**。
//          `MISO` 的高电平应当由**从机的推挽输出**提供（MCP3208 的 `DOUT` 是推挽），
//          ⛔ 而不是靠上拉。上拉的作用只是"**从机没驱动时不让线浮空**"（防输入级振荡/漏电）。
//    · ⇒ 结论 ②：⭐ **按键/开关**才真正需要上拉（它们是"开关到地"，靠上拉拉高），
//          而机械按键的**抖动是 ms 级**，与 100 ns 的上拉速度**完全不是一个量级**
//          ⇒ 上拉慢**不影响**按键，按键真正需要的是**去抖**（`debounce`）。
//    · ⇒ 结论 ③：⭐⭐ **无论上拉快慢，异步输入都必须做"同步 + （多比特）一致性处理"** ——
//          这才是防亚稳态的**正确手段**（上拉解决的是"电平不确定"，同步解决的是"时刻不确定"）。
//
// ⚠️ 本模块只做**同步**，不做去抖（去抖是 `debounce` 的事，属 `T14`）：
//    · 对**数据/时钟**类信号（SPI）：只需 2 级同步；
//    · 对**机械开关**：需要额外的**计数器去抖**（几 ms）。
// ─────────────────────────────────────────────────────────────────────────────
module sync_input #(
    parameter integer W      = 1,     // 位宽（多比特请**逐位**同步后再做一致性检查）
    parameter integer STAGES = 2,     // 同步级数（≥2）
    parameter [W-1:0] RESET_VAL = {W{1'b0}}
) (
    input  wire         clk,
    input  wire         rst_n,
    input  wire [W-1:0] async_in,
    output wire [W-1:0] sync_out
);

    (* async_reg = "true" *) reg [W-1:0] chain [0:STAGES-1];
    integer i;

    always @(posedge clk) begin
        if (!rst_n) begin
            for (i = 0; i < STAGES; i = i + 1) chain[i] <= RESET_VAL;
        end else begin
            chain[0] <= async_in;
            for (i = 1; i < STAGES; i = i + 1) chain[i] <= chain[i-1];
        end
    end

    assign sync_out = chain[STAGES-1];

endmodule

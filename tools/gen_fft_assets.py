"""Generate FFT coefficients (not PCM) and independent direct-DFT test vectors."""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
N_ROM = 2048


def generate():
    rom = ROOT / "rtl/hdmi/fft_coeff_rom.v"
    lines = ["// Generated by tools/gen_fft_assets.py; Q1.15 coefficients, NOT audio.",
             "module fft_coeff_rom(input wire clk_i, input wire [9:0] tw_addr_i,",
             " input wire [10:0] window_addr_i, output reg [31:0] twiddle_o,",
             " output reg [15:0] window_o);",
             " reg [31:0] twiddle[0:1023];", " reg [15:0] window[0:2047];",
             " initial begin"]
    for k in range(N_ROM // 2):
        c = round(32767 * math.cos(2 * math.pi * k / N_ROM))
        s = round(-32767 * math.sin(2 * math.pi * k / N_ROM))
        lines.append(f"  twiddle[{k}] = 32'h{((c & 65535) << 16) | (s & 65535):08X};")
    for k in range(N_ROM):
        w = round(32767 * (0.5 - 0.5 * math.cos(2 * math.pi * k / N_ROM)))
        lines.append(f"  window[{k}] = 16'h{w:04X};")
    lines += [" end", " always @(posedge clk_i) begin",
              "  twiddle_o <= twiddle[tw_addr_i];",
              "  window_o <= window[window_addr_i];", " end", "endmodule", ""]
    rom.write_text("\n".join(lines), encoding="ascii")
    data_dir = ROOT / "tb/data/fft"
    data_dir.mkdir(parents=True, exist_ok=True)
    for n in (64, 2048):
        generate_vectors(data_dir, n)
    print("PASS: coefficient assets and independent 64/2048-point DFT fixtures generated")


def generate_vectors(data_dir, n):
    rng = 0x54129
    noise = []
    for _ in range(n):
        rng = (1664525 * rng + 1013904223) & 0xffffffff
        noise.append((rng >> 16) % 24001 - 12000)
    frames = [[0] * n, [10000] * n,
              [round(12000 * math.sin(2 * math.pi * 5 * k / n)) for k in range(n)],
              [round(10000 * math.cos(2 * math.pi * 3 * k / n)
                     + 6000 * math.sin(2 * math.pi * 13 * k / n)) for k in range(n)],
              [6000 if k % 2 == 0 else -6000 for k in range(n)], noise]
    samples = []
    bins = []
    for frame in frames:
        samples.extend(f"{v & 65535:04X}" for v in frame)
        # Independent O(N^2) mathematical DFT, no radix-2 butterfly model.
        windowed = [v * (0.5 - 0.5 * math.cos(2 * math.pi * k / n))
                    for k, v in enumerate(frame)]
        for b in range(n // 2 + 1):
            r = round(4 / n * sum(v * math.cos(2 * math.pi * b * k / n)
                                 for k, v in enumerate(windowed)))
            i = round(-4 / n * sum(v * math.sin(2 * math.pi * b * k / n)
                                  for k, v in enumerate(windowed)))
            bins.append(f"{((r & 0x3ffff) << 18) | (i & 0x3ffff):09X}")
    (data_dir / f"input{n}.hex").write_text("\n".join(samples) + "\n", encoding="ascii")
    (data_dir / f"dft{n}.hex").write_text("\n".join(bins) + "\n", encoding="ascii")


if __name__ == "__main__":
    generate()

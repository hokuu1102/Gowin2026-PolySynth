/*
 * ⭐⭐⭐ 放水限流（🔴 2026-09-23 重做 —— 原来是"限帧数"，那是错的）
 * ---------------------------------------------------------------------------
 * 🔴 旧做法的两个问题：
 *   ① `BLE_POOL_MAX_FRAMES_PER_PUMP = 64`（帧）配 2 ms 周期
 *      ⇒ 理论 32,000 帧/s，⚠️ 而 FPGA 只消费 ~69.5 事件/s ⇒ **快 460 倍**
 *   ② 🔴 **`vTaskDelay(2ms)` 只是"至少 2 ms"** —— 被调度器延迟后，
 *      `elapsed` 与 `due_tick` 会【累积变大】⇒ 下一轮一次发更多 ⇒ ⚠️ 突发
 *
 * ⭐ 新做法：**按【tick】限流，⛔ 不按帧数** ——
 *    单轮最多把 `due_tick` 推进 `BLE_POOL_MAX_TICK_ADVANCE` 个 tick。
 *
 * ⭐ 取值依据（⚠️ 2026-09-30 【重算】—— 原依据用错了周期，🔴 见下方更正）：
 *
 * 🔴🔴 **更正记录：原注释按 `pump 周期 2 ms` 算，⚠️ 而【实际周期是 ~14 ms】**
 * ---------------------------------------------------------------------------
 * ⭐ 实测（2026-09-30）：
 *   · `task_pool_pump` 用 `BLE_DELAY_TICKS_AT_LEAST_1(2)`
 *   · `CONFIG_FREERTOS_HZ = 100` ⇒ `pdMS_TO_TICKS(2) = 0` ⇒ 被抬到 **1 tick = 10 ms**
 *   · ⚠️ 再叠加任务执行时间与调度抖动 ⇒ ⭐ **实测轮周期 P ≈ 14 ms**
 *     （⭐ 反推：P = 31 tick ÷ 2217 tick/s ≈ 13.98 ms）
 *
 * 🔴 **⇒ 原注释"正常一轮推进 3.8 tick、取 8 倍余量 31"是【基于错误周期】的**：
 *     按真实 P≈14 ms，一轮【本应】推进 `1920 × 0.014 = 26.9 tick`
 *     ⇒ **31 只剩 1.15 倍余量**（⛔ 不是 8 倍）。
 *
 * ⭐⭐ **更关键的量纲问题**：限流上限对应的速率必须 **≥ 音乐速率**，
 *     否则 🔴 **固件会被上限【顶住】跑不快 ⇒ 必然偏慢**。
 *       · 上限速率 = `MAX_TICK_ADVANCE / P`
 *       · 要求 `≥ 1920 tick/s` ⇒ `MAX_TICK_ADVANCE ≥ 1920 × P`
 *     ⚠️ 而原值 31 配 P≈14 ms ⇒ 上限 **2217 tick/s** ⇒ 略高于音乐
 *     ⇒ ⚠️ **一旦因首轮欠账或任何抖动落后，它就会以上限速率"追赶"**
 *     ⇒ 🔴 **表现为放水偏快（pace < 1）** —— ⭐ 这正是实测到的现象。
 *
 * ⭐ 取值依据（⭐ 新）：
 *    · 音乐速率 = `BPM×PPQN/60 = 1920 tick/s`（@120 BPM / PPQN=960）
 *    · 轮周期按 **P ≈ 14 ms** 保守估计 ⇒ 一轮本应推进 **≈ 27 tick**
 *    · ⭐ 取 **26** ⇒ 上限速率 = `26 / 0.014 = 1857 tick/s`
 *      ⇒ ⭐ **略低于音乐速率** ⇒ ✅ 落后时**只能慢慢还**，⛔ 不会超速
 *      ⭐ 这符合 `pool.c` 的纪律「**宁可饿着（可见 underrun），不可撑着（静默溢出）**」
 *    · ⚠️ 取整为 26（⭐ 若将来把轮周期改成 10 ms，应改为 ≈ 19）
 *
 * 🔴 **⛔ 不要为了"追得上"而调大本值** ——
 *    ⚠️ 那会让上限速率高于音乐速率 ⇒ 🔴 **正是"撑着"的那一侧**。
 *    ⭐ 真的要更快，应该【提高 pump 频率】（⛔ 不是放宽限流）。
 *
 * ⚠️ 副作用（⭐ 这是【故意】的、且是安全的）：
 *    若 ESP32 被长时间卡住，`due_tick` 会落后。
 *    ⭐ 新逻辑【不追赶】—— 每轮只推进有限 tick，落后会慢慢积累（`late_ticks_max` 看得见）。
 *    ⭐ 这正是我们想要的：**宁可 FPGA underrun（可见），⛔ 不要缓冲溢出（静默丢）**。
 */
#define BLE_POOL_MAX_TICK_ADVANCE     26u

/*
 * ⚠️ 保留一个【帧数】硬上限 —— 防病态情况
 *    （⭐ 比如某一 tick 内有海量事件，tick 限流管不住帧数）
 *
 * ⚠️ 取值依据：**FPGA 缓冲 = 1024 事件** ⇒
 *    单轮最多发 **512**（一半）—— ⚠️ 保证即使连发两轮也不会灌满。
 *    ⭐ 正常曲谱一轮只有几帧，这个上限【平时根本碰不到】。
 */
#define BLE_POOL_MAX_FRAMES_PER_PUMP  512u

/* pump 周期（ms） */
#define BLE_POOL_PUMP_PERIOD_MS       2

/* ===========================================================================
 * 9b. 🔴 空转任务的【安全延时】—— ⛔ 不要直接用 pdMS_TO_TICKS(小值)
 * ===========================================================================
 * 🔴 上机实测缺陷（2026-09-24，COM29）：
 *    Task watchdog 5 s 触发，`- IDLE0 (CPU 0)`、`CPU 0: drain`，
 *    栈回溯 = task_drain @ ble_main.c:484 → vTaskDelay。
 *
 * ⭐ 根因：`pdMS_TO_TICKS()` 是【整数除法】，且本工程
 *    `CONFIG_FREERTOS_HZ = 100`（⇒ 1 tick = 10 ms）：
 *
 *      pdMS_TO_TICKS(1) = (1 * 100) / 1000 = 0    🔴
 *      pdMS_TO_TICKS(2) = (2 * 100) / 1000 = 0    🔴
 *      pdMS_TO_TICKS(9) = (9 * 100) / 1000 = 0    🔴
 *      pdMS_TO_TICKS(10)= (10* 100) / 1000 = 1    ✅
 *
 * ⇒ ⚠️ **任何 < 10 ms 的值在 100 Hz 下全部塌成 0** ⇒
 *    `vTaskDelay(0)` 几乎不延时，只触发一次任务切换 ⇒
 *    ⚠️ 若该任务是最高优先级就绪任务，会【立刻被调度回来】⇒
 *    🔴 **忙循环**（每秒上千次）⇒ **饿死同核 IDLE0** ⇒
 *    🔴 **IDLE 任务正是靠运行来喂看门狗** ⇒ **5 s 后 TWDT 必然触发**。
 *
 * ⭐ 本工程的受害点（两处，均为优先级 9）：
 *    · `ble_main.c` `task_drain()` —— 缓冲空时 `pdMS_TO_TICKS(1)` = 0
 *    · `pool.c`     `task_pool_pump()` —— `pdMS_TO_TICKS(2)` = 0
 *
 * ⭐ 对策：统一走本宏 —— **保证至少 1 tick**（⛔ 永不塌成 0）。
 *    ⚠️ 语义与原意一致（"想等就得让出 CPU"），
 *       只是把"小于 1 tick 的请求"抬到 1 tick（本工程 = 10 ms）。
 */
#define BLE_DELAY_TICKS_AT_LEAST_1(ms) \
    ((pdMS_TO_TICKS(ms) > 0) ? pdMS_TO_TICKS(ms) : 1)

/* ===========================================================================
 * 9c. ⭐⭐ 起播触发（2026-09-30 新增）
 * ===========================================================================
 * 🔴 **为什么需要它**：`pool_start()` 原来【零调用】⇒ `s_running` 恒 false
 *    ⇒ 🔴 **`GPIO17` 永远不发数据**（⚠️ 日志里 `sent=` 恒为 0）。
 *
 * ⚠️⚠️ **背景：起播归谁管 —— 这是一个【尚未裁定】的架构问题。**
 *    · FPGA 侧拍板过「方案③：**上板手动按键起播**，⛔ 你那边不用改固件」
 *      （`files/20-代码/FPGA侧答复-ESP32对接清单-20260923.md:24/58`）
 *      ⭐ 但那句话的隐含前提是 **ESP32 只当透传管道（= 模式 A）**。
 *    · ⚠️ 而本工程实现的是**模式 B**（ESP32 自己按谱子时间放水）
 *    · 🔴 **⇒ 两者互斥**：模式 B 下起播必须由 ESP32 决定，
 *       否则【时间基准对不齐】（⭐ `pool_start()` 把谱面 t=0 锚在
 *       **ESP32 的 `esp_timer`** 上，见 `pool.c:461-462`）。
 *
 * 🔴 **⇒ 完整分析见 `files/20-代码/矛盾裁定单-方案3与模式B-20260930.md`。**
 *    ⚠️ **本节的实现【不预设裁定结果】** —— 它只是让"能起播"这件事可测。
 *
 * ⭐ 三种触发方式（⚠️ 编译期三选一，见下方 `BLE_START_TRIGGER`）：
 *    · `SERIAL` —— ⭐ **默认**。从 UART1 **RX（`GPIO18`）** 收单个 ASCII 字符：
 *        `S` = start（起播）  `X` = stop（停）  `R` = reset（清池）
 *      ⚠️ 注意：这是**给 FPGA 的那条 UART 的【接收方向】**，
 *         ⭐ 所以"按键"可以用 PC 串口 / USB-TTL **从远端模拟**，
 *         ⚠️ 上板后 FPGA 也能发（⭐ 但 FPGA 当前不发这些字符）。
 *      ⭐ 选它的理由：**⛔ 不需要额外接线**，现在就能测。
 *    · `GPIO`   —— ⭐ 用**外接按键**（⭐ 引脚见下方 `BLE_BTN_GPIO`），按下即起播。
 *      🔴🔴 **2026-10-01 更正**：⚠️ 原文写「用板载 **BOOT 键（`GPIO0`）**」⇒ 【已作废】——
 *         ⭐ **2026-09-30 已把按键从 `GPIO0` 改到 `GPIO6`**（⭐ 理由见下方 §9b：`GPIO0` 是 strapping 脚）。
 *         ⭐ **现值 = `BLE_BTN_GPIO = 6`**（本文件 `:425`），⭐ 接线 = 一端 `GPIO6`、另一端 `GND`（低有效）。
 *    · `NONE`   —— 关掉（⚠️ 回到"零调用"状态，`sent=` 会一直是 0）。
 */
#define BLE_START_TRIG_SERIAL   0
#define BLE_START_TRIG_GPIO     1
#define BLE_START_TRIG_NONE     2

#ifndef BLE_START_TRIGGER
#define BLE_START_TRIGGER       BLE_START_TRIG_SERIAL   /* ⭐ 默认：串口字符触发 */
#endif

/* ⭐ 按键引脚（⭐ 低有效，按下接地；⭐ 2026-09-30 从 GPIO0 改到 GPIO6）
 * ---------------------------------------------------------------------------
 * 🔴 **为什么不用板载 BOOT 键（GPIO0）** —— ⚠️ 它是【strapping 脚】：
 *    · ⭐ 官方（esptool Boot Mode Selection）：
 *      「The ESP32-S3 will enter the serial bootloader when **GPIO0 is held
 *        low on reset**」
 *      ⇒ 🔴 **按着 BOOT 键上电/复位 ⇒ 进下载模式,程序不跑**
 *        ⚠️ 症状是"串口一片安静" ⇒ ⚠️ **极易被误判成固件坏了**
 *    · 🔴 GPIO0 有 **45 kΩ 内部上拉**（官方明确）⇒ ⚠️ 接外部按键
 *      **必须用强下拉**（如 10 kΩ 到 GND），⛔ 否则可能压不下去
 *    · ⚠️ 板载 USB 的 `DTR` 就接在 `GPIO0` 上 ⇒ ⚠️ 有程序开关 `COMx`
 *      时若拉 DTR，可能**误触发复位/进下载**
 *  ⇒ ⭐ **结论：GPIO0 可以开发期凑合，⛔ 不能当产品按键。**
 *
 * ⭐ **选 `GPIO6` 的理由（⭐ 逐条排除了所有冲突）**：
 *    | 排除项 | 说明 |
 *    |---|---|
 *    | strapping | ⛔ 不是（`0/45/46` 才是） |
 *    | SPI flash / PSRAM | ⛔ 不是（`26~37` 是，⭐ 本模组八线 PSRAM） |
 *    | 原生 USB | ⛔ 不是（`19/20` 才是） |
 *    | 板载 RGB LED | ⛔ 不是（⭐ 本工程明确警告避开 `38/48`） |
 *    | 本固件已占用 | ⛔ 不是（UART1=`17/18`、UART0=`43/44`、UART2=`4/5`） |
 *    ⭐ 且它与串口屏的 `GPIO4/5` **相邻** ⇒ ⚠️ 接线方便。
 *
 * ⚠️ 接线：⭐ **按键一端接 `GPIO6`，另一端接 `GND`**（⭐ 低有效）。
 *    ⭐ 内部上拉已启用（`gpio_config` 里 `pull_up_en`）⇒ ⚠️ **外接上拉可省**，
 *    但 ⚠️ 长线/干扰环境建议**外加 10 kΩ 上拉到 3.3 V**。
 *    ⚠️ 建议串 **100 nF 到 GND** 做硬件消抖（⭐ 软件消抖也已开启）。
 */
#define BLE_BTN_GPIO            6
/* ⚠️ 消抖与轮询周期（⚠️ 都 ≥ 10 ms 才不会被 `pdMS_TO_TICKS` 塌成 0） */
#define BLE_BTN_POLL_MS         10
#define BLE_BTN_DEBOUNCE_MS     30


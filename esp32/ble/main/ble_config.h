/*
 * ble_config.h -- ESP32-S3 BLE 透传桥 · 可配置项
 * ============================================================================
 * 项目：FPGA2026 · ESP32 通路（⭐ S3 / BLE 版）
 *
 * ⚠️ 本文件是【唯一】需要按现场改的地方。
 *
 * ============================================================================
 * 🔴 与 SPP 版（esp32/bridge/）的关键差异 —— ⛔ 不要混用两者的假设
 * ============================================================================
 *  | | SPP 版（初代 ESP32）    | ⭐ 本版（ESP32-S3）        |
 *  |---|---|---|
 *  | 蓝牙     | 经典 BR/EDR + SPP  | 🔴 **只有 BLE**（S3 无 BR/EDR） |
 *  | PC 侧    | ⭐ 配对后是个 **COM 口** | 🔴 **不是 COM 口** ⇒ `evt2uart.py` **不能直接用** |
 *  | 手机侧   | 通用"蓝牙串口助手"      | ⭐ 需 **BLE 终端 App**（支持自定义 UUID 的） |
 *  | PSRAM    | ⚠️ 买不到带 PSRAM 的板 | ⭐ **有**（S3 那块）⇒ 水池可以放整曲 |
 *
 * ⭐ 为什么会有这一版：⚠️ 初代 ESP32 + PSRAM 的开发板买不到，
 *    而手上那块 S3 【有 PSRAM】 ⇒ 用 S3 走 BLE 换取大水池。
 *    ⚠️ 代价：PC 侧生态不如 SPP 方便（见上表）。
 * ============================================================================
 */
#ifndef BLE_CONFIG_H
#define BLE_CONFIG_H

/* ---------------------------------------------------------------------------
 * 1. 帧格式（⭐ 冻结契约，⛔ 别改 —— 与 SPP 版逐位一致）
 * ---------------------------------------------------------------------------
 * byte 0    : 0xA5          帧头（固定魔数）
 * byte 1..8 : 64 bit 事件   大端
 *
 * ⭐⭐⭐ 三种 9 字节块（ESP32 靠【帧头】区分，⛔ 不是靠位置）
 * ---------------------------------------------------------------------------
 *  ① 帧头 = 0xA5  ⇒ ⭐ **事件帧** ⇒ ✅ **转发给 FPGA**
 *  ② 帧头 = 0x00  ⇒ ⭐ **总数帧** ⇒ ⛔ **ESP32 自己留下**（见下）
 *  ③ 全 9 字节 = 0xA5 ⇒ ⭐ **复位标记** ⇒ ⛔ **丢弃**（⚠️ 与 FPGA 侧同一定义）
 *
 * 🔴 为什么总数帧用 `0x00` 开头：
 *    ⭐ 事件帧帧头是 `0xA5` ⇒ ⛔ **永不撞车**（⭐ 比"约定某个位置"可靠）。
 *
 * 🔴 为什么总数帧也是 **9 字节**：
 *    ⭐ 这样 ESP32 的 **9N 对齐逻辑一行都不用改** ——
 *      它照样按 9 字节切，⭐ 只是看帧头决定"转发还是自己留下"。
 */
#define FRAME_BYTES          9

/* 事件帧帧头（⭐ 冻结值，与 FPGA 侧 `evt_uart_rx.v` 一致） */
#define FRAME_HDR_EVENT      0xA5u

/* ⭐ 总数帧帧头（ESP32 内部约定；⛔ FPGA 永远看不到它） */
#define FRAME_HDR_TOTAL      0x00u

/* ---------------------------------------------------------------------------
 * 2. 波特率（⭐ 与 FPGA 侧一致）
 * ---------------------------------------------------------------------------
 * ⭐ 目标 1,000,000（1 Mbps）
 * 🔴 FPGA 侧现值仍是 115200 ⇒ 两边必须一致，这里做成可配置。
 */
#ifndef BLE_BAUD
#define BLE_BAUD             1000000
#endif

/* ---------------------------------------------------------------------------
 * 3. 引脚（给 FPGA 的 UART2）
 * ---------------------------------------------------------------------------
 * ⚠️ 必须【交叉接】：
 *      ESP32 TX(GPIO17) -> FPGA UART2_RX(G22)
 *      ESP32 RX(GPIO18) <- FPGA UART2_TX(G21)
 *
 * 🔴 GPIO43/44 是 U0 日志口，⛔ 不要占用。
 * 🔴🔴 【S3 特有】若模组带 PSRAM（如 ESP32-S3-WROOM-1-N16R8），
 *      **GPIO35/36/37 被八线 PSRAM 占用**，且 **GPIO26~32 也常用于 flash/PSRAM**
 *      ⇒ ⭐ 改引脚前必须对照具体模组的 datasheet。
 *      ⭐ 这里选 GPIO17/18 —— 在 S3 上是安全的通用 IO（⛔ 不是 USB 脚）。
 *      ⚠️ GPIO19/20 是 S3 的原生 USB（D-/D+），⛔ 不要当普通串口用。
 */
#define BLE_UART_PORT        UART_NUM_1
#define BLE_PIN_UART_TX      17
#define BLE_PIN_UART_RX      18

/* 日志口（UART0）—— ⚠️ S3 上默认走 GPIO43/44 */
#define BLE_LOG_UART_PORT    UART_NUM_0
#define BLE_PIN_LOG_TX       43
#define BLE_PIN_LOG_RX       44

/* ---------------------------------------------------------------------------
 * 4. UART 缓冲
 * ---------------------------------------------------------------------------
 * ⚠️ TX 缓冲取 9 的整数倍（1026 = 9×114），使块边界天然落在帧边界上。
 */
#define BLE_UART_TX_BUF      (FRAME_BYTES * 114)   /* 1026 B */
#define BLE_UART_RX_BUF      (FRAME_BYTES * 114)   /* 1026 B */

/* ---------------------------------------------------------------------------
 * 5. ⭐ BLE 参数
 * ---------------------------------------------------------------------------
 * ⚠️ 设备名：手机/PC 靠它找设备。⛔ 不要写含人名的字符串。
 */
#define BLE_DEV_NAME         "FPGA2026-Synth"

/*
 * 🔴 GATT UUID —— ⭐ **照抄 ESP-IDF 官方 `ble_spp_server` 示例**
 *    来源（⭐ 我实际拉取了源码核对，⛔ 不是凭印象）：
 *      esp-iot-solution/examples/bluetooth/ble_conn_mgr/ble_spp/spp_server/main/app_main.c
 *
 *    官方原文定义：
 *        #define BLE_SVC_SPP_UUID16      0xABF0   // ⭐ 服务
 *        #define BLE_SVC_SPP_CHR_UUID16  0xABF1   // ⭐ 特征
 *
 *    ⚠️⚠️ 这里踩过一个【我自己的认知错误】，⚠️ 记下来免得后人再错：
 *       我原以为"服务是 128 位 vendor UUID、0xABF1 挂在它下面"。
 *       🔴 实际官方**服务和特征都是【16 位】标准 UUID**：
 *           服务   = 0xABF0
 *           接收   = 0xABF1   （对端写数据进来）
 *           通知   = 0xABF2   （我们发出去）
 *           命令   = 0xABF3
 *           状态   = 0xABF4
 *       ⭐ 用 16 位反而【更好】—— 现成 BLE 终端 App 填 UUID 时更省事。
 *
 *    ⚠️ 另一条：官方示例走的是 `esp_ble_conn_mgr` 高层组件，
 *       而我们用**原生 Bluedroid API** ⇒ ⛔ **只能照抄 UUID 定义，
 *       不能照抄它的调用方式**（两者 API 完全不同）。
 */
#define BLE_SVC_UUID16        0xABF0
#define BLE_CHR_RECV_UUID16   0xABF1   /* ⭐ 对端写这里 */
#define BLE_CHR_NOTI_UUID16   0xABF2   /* ⭐ 我们 notify 这里 */
#define BLE_CHR_CMD_UUID16    0xABF3
#define BLE_CHR_STAT_UUID16   0xABF4

/*
 * ⚠️ MTU：⚠️ 默认 ATT MTU = 23（有效载荷仅 20 字节）。
 *    整曲 104 KB 若按 20 字节一包发 ⇒ **5200 多包** ⇒ ⚠️ 慢且易错。
 *    ⭐ 所以必须在对端连接后【协商更大 MTU】。
 *    ⚠️ 但能协商到多少由【对端】决定：
 *        · 手机 App 常见 247 / 512
 *        · Windows 常给 517 或 185
 *    ⭐ 这里设"期望值"，实际以协商结果为准（⚠️ 会在日志里打出来）。
 */
#define BLE_PREFERRED_MTU    517

/* ---------------------------------------------------------------------------
 * 6. ⭐ 转发模式（与 SPP 版同构）
 * ---------------------------------------------------------------------------
 *   模式 A：纯透传   —— PC/手机 限速发，ESP32 收到就转（9N 对齐）
 *   模式 B：二级水池 —— ESP32 缓存整曲 + 自己按谱子时间放水
 *
 * ⚠️ 两模式共用同一套 9N 对齐与写 UART 路径。
 *
 * ⭐ 默认改为 **模式 B**（2026-09-23 用户拍板）：
 *    ⭐ 理由：S3 那块**有 PSRAM**，水池放得下整曲（104.3 KB）⇒
 *           ⭐ **PC 侧零限速**（一口气灌完即可），⭐ 节奏由 ESP32 自己管。
 *    ⚠️ 要用模式 A：`idf.py -DBLE_MODE=0 build`
 */
#define BLE_MODE_A_PASSTHROUGH   0
#define BLE_MODE_B_POOL          1

#ifndef BLE_MODE
#define BLE_MODE             BLE_MODE_B_POOL      /* ⭐ 默认模式 B */
#endif

/* ---------------------------------------------------------------------------
 * 7. 任务优先级与状态打印
 * ---------------------------------------------------------------------------
 */
#define BLE_TASK_PRIO_DRAIN     9
#define BLE_TASK_PRIO_UART_RX   8
#define BLE_TASK_PRIO_STATUS    4
#define BLE_STATUS_PERIOD_MS    1000

/* ---------------------------------------------------------------------------
 * 8. 反向通路（UART -> BLE）
 * ---------------------------------------------------------------------------
 */
#define BLE_TX_CHUNK         244      /* ⚠️ 不超过协商 MTU-3 */
#define BLE_TX_GAP_MS        2

/* ===========================================================================
 * 9. ⚠️ 水池参数（⭐ 无条件定义 —— ⛔ 不要放回 #if 里面）
 * ===========================================================================
 * 🔴 这里在 SPP 版踩过真 bug：宏被 `#if BLE_MODE==...` 挡住，而 pool.c 是
 *    【无条件编译】的 ⇒ 模式 A 下编不过（'undeclared'）。⇒ 一律无条件定义。
 */

/*
 * ⭐ 水池【期望】容量。
 *
 * ⭐ 本版（S3 + PSRAM）比 SPP 版的优势就在这里：
 *    SPP 版：内部 DRAM 只剩 77.8 KB < 整曲 104.3 KB ⇒ 🔴 装不下整曲
 *    本  版：⭐ **有 PSRAM（S3 那块）** ⇒ 整曲轻松放下
 *
 * ⚠️ 实际拿到多少由 pool.c 的 pool_alloc() 决定（优先 PSRAM，退化内部 DRAM）。
 */
#define BLE_POOL_BYTES       (160 * 1024)   /* ⭐ 整曲 104.3 KB + 余量 */

/*
 * ⭐ 提前量（tick）—— 与 SPP 版同一取值与依据。
 *
 *   FPGA 缓冲 8 KB = 1024 事件（🔵 2026-09-23 FPGA 侧已采纳）。
 *   最密曲 夜洋风景 = 99.3 事件/小节，PPQN=960
 *   => 1024 事件 ≈ 39,600 tick
 *   ⇒ ⭐ 取 20,000 tick（≈5.2 小节 ≈ 517 事件）—— 占 FPGA 缓冲约一半，留一半余量。
 *
 *   🔴 太大 ⇒ FPGA 缓冲溢出（静默丢）；⚠️ 太小 ⇒ 一卡就 underrun（掉音）
 */
#define BLE_POOL_LEAD_TICKS      20000u

/* 默认 tick_inc（120 BPM @ PPQN=960, 50 MHz）= round(2^32*2*960/50e6) */
#define BLE_POOL_DEFAULT_TICK_INC  164927u

/*
 * ⭐⭐⭐ 放水限流（🔴 2026-09-23 重做 —— 原来是"限帧数"，那是错的）
 * ---------------------------------------------------------------------------
 * 🔴 旧做法的两个问题：
 *   ① `BLE_POOL_MAX_FRAMES_PER_PUMP = 64`（帧）配 2 ms 周期
 *      ⇒ 理论 32,000 帧/s，⚠️ 而 FPGA 只消费 ~69.5 事件/s ⇒ **快 460 倍**
 *   ② 🔴 **`vTaskDelay(2ms)` 只是"至少 2 ms"** —— 被调度器延迟后，
 *      `elapsed` 与 `due_tick` 会【累积变大】⇒ 下一轮一次发更多 ⇒ ⚠️ 突发
 *
 * ⭐ 新做法：**按【tick】限流，⛔ 不按帧数** ——
 *    单轮最多把 `due_tick` 推进 `BLE_POOL_MAX_TICK_ADVANCE` 个 tick。
 *
 * ⭐ 取值依据（⚠️ 算出来的，⛔ 不是拍的）：
 *    1 tick = 520.83 us（`BLE_POOL_DEFAULT_TICK_INC` @ 120 BPM / PPQN=960 / 50 MHz）
 *    pump 周期 2 ms ⇒ ⭐ **正常一轮只应推进 3.8 tick**
 *    ⇒ 取 **约 8 倍余量 = 31 tick**（⭐ 容忍调度抖动，⛔ 又不至于突发）
 *    31 tick = 16.1 ms 谱面时间 = 提前量(20000) 的 **0.15%**
 *
 * ⚠️ 副作用（⭐ 这是【故意】的、且是安全的）：
 *    若 ESP32 被长时间卡住，`due_tick` 会落后。
 *    ⭐ 新逻辑【不追赶】—— 每轮只推进 31 tick，落后会慢慢积累（`late_ticks_max` 看得见）。
 *    ⭐ 这正是我们想要的：**宁可 FPGA underrun（可见），⛔ 不要缓冲溢出（静默丢）**。
 */
#define BLE_POOL_MAX_TICK_ADVANCE     31u

/*
 * ⚠️ 保留一个【帧数】硬上限 —— 防病态情况
 *    （⭐ 比如某一 tick 内有海量事件，tick 限流管不住帧数）
 *
 * ⚠️ 取值依据：**FPGA 缓冲 = 1024 事件** ⇒
 *    单轮最多发 **512**（一半）—— ⚠️ 保证即使连发两轮也不会灌满。
 *    ⭐ 正常曲谱一轮只有几帧，这个上限【平时根本碰不到】。
 */
#define BLE_POOL_MAX_FRAMES_PER_PUMP  512u

/* pump 周期（ms） */
#define BLE_POOL_PUMP_PERIOD_MS       2

/* ===========================================================================
 * 10. ⭐ 串口屏（与 SPP 版同一套，走 UART2）
 * ===========================================================================
 * 屏型号：⭐ TJC3224T120_011R_A01（T1 系列 2.0 寸，电阻触摸，320×240）
 *
 * ⚠️ 电平（🔵 2026-09-23 用户确认）：
 *      · **串口信号电平 = 3.3 V** ✅ ⇒ ⭐ **可与 ESP32 直连，⛔ 不需要电平转换**
 *      · ⚠️ 但**供电 VCC 仍是 4.65~6.5 V** ⇒ 🔴 **必须给 5 V**
 *      ⭐ 关键区分：**"信号 3.3 V" ≠ "供电 3.3 V"** ——
 *        信号线直连没问题，⛔ 但 VCC 接 3.3 V 屏根本不亮。
 *
 * ⚠️ 引脚注意：本版 UART1 已给 FPGA（GPIO17/18）⇒ 屏改用 UART2。
 *    🔴 这与 SPP 版【正好相反】（那边 UART1=屏、UART2=FPGA）——
 *       ⚠️ 因为 S3 的 UART 编号与可用引脚不同，⛔ 别照抄 SPP 版的引脚。
 */
#ifndef BLE_HMI_ENABLE
#define BLE_HMI_ENABLE       1          /* 0 = 不接屏 */
#endif

#define BLE_HMI_UART_PORT    UART_NUM_2
#define BLE_HMI_BAUD         115200
#define BLE_PIN_HMI_TX       4
#define BLE_PIN_HMI_RX       5

#define BLE_HMI_BOOT_DELAY_MS   300
#define BLE_HMI_WAIT_BOOT_ACK   1
#define BLE_HMI_BOOT_ACK_MS     2000
#define BLE_HMI_REFRESH_MS      200
#define BLE_HMI_CMD_MAX         96

#endif /* BLE_CONFIG_H */

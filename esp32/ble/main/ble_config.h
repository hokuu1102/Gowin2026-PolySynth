/* ---------------------------------------------------------------------------
 * 12. ⭐⭐ 板载 WS2812 RGB 灯（⭐ 2026-09-30 夜新增，用户 Q4 裁定）
 * ---------------------------------------------------------------------------
 * ⭐ 用户原话：「蓝牙连好了可以让灯亮一下」＋「开发板上好像有现成的 ws2812」
 *
 * ⭐ 已核实的硬件事实：
 *   · 板子 = ESP32-S3-DevKitC-1
 *   · 板载 RGB = ⭐ WS2812（⭐ 可寻址，⛔ 不是普通三色 LED）
 *   · 数据脚 = ⭐ GPIO48
 *
 * 🔴🔴 必须知道的硬件坑（⚠️ 否则"代码全对但灯不亮"）：
 *   板上 R17 与 GPIO48 之间出厂是【断开】的 ⇒
 *   ⭐ 必须用跳线把 RGB 下方的焊点短接，灯才会亮。
 *   ⇒ ⚠️ 若上板"灯不亮但日志说 init OK"，先查这个跳线，⛔ 别改代码。
 *
 * ⚠️ 与 BLE_LED_ENABLE（普通 GPIO 驱动【外部】LED）的区别：
 *    · WS2812_ENABLE  ⇒ ⭐ 板载那颗（⭐ 无需接线，⚠️ 但要短接跳线）
 *    · BLE_LED_ENABLE ⇒ ⚠️ 外接 LED（⭐ 要接线）
 *   ⭐ 两者可同时开（⚠️ 但通常只用一个）。
 *
 * 🔴🔴 **2026-10-01：默认【关闭】—— 安全优先**（⭐ 用户："先把灯关了，安全第一"）
 *
 * ⚠️ 用户提出的关键点：⭐ **WS2812 有【锁存】**
 *    ⇒ ⭐ 它把**最后一次收到的 24 位值锁住**，⚠️ 直到收到**新的完整帧**才改变
 *    ⇒ 🔴 **即使固件停了 / GPIO 空闲 / 甚至 ESP32 重启，
 *         只要不复位灯珠供电，它就一直亮着**。
 *
 * ⭐⭐ **所以"把代码关掉"【不够】** —— 必须**再显式发一次全 0**去清锁存。
 *    ⇒ ⭐ 本工程的做法（⭐ 两层）：
 *      ① `WS2812_ENABLE = 0`  ⇒ ⛔ 不用它做任何指示（⭐ 不会点亮）
 *      ② `WS2812_CLEAR_ON_BOOT = 1` ⇒ ⭐ **开机发一次全 0**，
 *         把**上一次遗留下来的锁存值清掉** ⇒ ✅ **保证灭**
 *    ⚠️ 只做①不做② ⇒ 🔴 **灯可能还停在旧颜色上**（⭐ 因为锁存还在）。
 */
#define WS2812_ENABLE        0        /* ⭐ 0 = 不用板载灯（⭐ 安全默认，2026-10-01） */
#define WS2812_GPIO          48       /* ⭐ 板载 WS2812 数据脚（⭐ 已核实） */
/*
 * ⭐ 开机清一次锁存（⭐ 与 `WS2812_ENABLE` **独立** —— ⚠️ 这点很重要）：
 *    · `WS2812_ENABLE=0` + `CLEAR=1` ⇒ ⭐ **清掉旧颜色后不再点亮**（✅ 安全默认）
 *    · `WS2812_ENABLE=1`              ⇒ ⭐ 正常当指示灯用（⭐ 此时开不开清都行）
 * ⚠️ 若确认灯已经灭透了，⭐ 可以把这条也设 0（⚠️ 但**留着无害**）。
 */
#define WS2812_CLEAR_ON_BOOT 1        /* ⭐ 1 = 开机发全 0 清锁存 */


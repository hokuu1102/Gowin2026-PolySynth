/*
 * bridge_config.h -- ESP32 SPP<->UART 透传桥 · 可配置项
 * ============================================================================
 * 项目：FPGA2026 纯硬件实时音频合成 · ESP32 通路
 *
 * ⚠️ 本文件是【唯一】需要按现场改的地方。
 * ============================================================================
 */
#ifndef BRIDGE_CONFIG_H
#define BRIDGE_CONFIG_H

/* ---------------------------------------------------------------------------
 * 1. 帧格式（⭐ 冻结契约，⛔ 别改）
 * ---------------------------------------------------------------------------
 * byte 0    : 0xA5          帧头（固定魔数）
 * byte 1..8 : 64 bit 事件   大端
 *
 * 见 files/20-代码/play_seq接口冻结契约.md
 */
#define FRAME_BYTES          9

/* ⭐⭐⭐ 三种 9 字节块（ESP32 靠【帧头】区分，⛔ 不是靠位置）
 * ---------------------------------------------------------------------------
 *  ① 帧头 = 0xA5  ⇒ ⭐ **事件帧** ⇒ ✅ **转发给 FPGA**
 *  ② 帧头 = 0x00  ⇒ ⭐ **总数帧** ⇒ ⛔ **ESP32 自己留下**（byte1..8 = 大端总数）
 *  ③ 全 9 字节 = 0xA5 ⇒ ⭐ **复位标记** ⇒ ⛔ **丢弃**（⚠️ 与 FPGA 侧同一定义）
 *
 * 🔴 为什么总数帧用 `0x00` 开头：⭐ 事件帧帧头是 `0xA5` ⇒ ⛔ **永不撞车**
 * 🔴 为什么总数帧也是 9 字节：⭐ **9N 对齐逻辑一行都不用改**
 *
 * 🔴 为什么过滤必须在 ESP32 做：⭐ FPGA 只认 `0xA5` 帧头 ——
 *    别的帧头到了它那里 ⇒ `hdr_err_cnt_o++`（⚠️ 本该是 0，是验收判据）
 *    且载荷会被当成一个【真事件】⇒ 🔴 弹出随机音符。
 */
#define FRAME_HDR_EVENT      0xA5u   /* 事件帧帧头（⭐ 冻结，与 FPGA 一致） */
#define FRAME_HDR_TOTAL      0x00u   /* ⭐ 总数帧帧头（ESP32 内部约定） */

/* ---------------------------------------------------------------------------
 * 2. 波特率
 * ---------------------------------------------------------------------------
 * ⭐ 目标值 = 1,000,000（1 Mbps，与 FPGA 侧一致）
 *
 * 🔴 但 FPGA 侧【现在实际是 115200】：
 *      rtl/w3c/uart_rx.v:47     BAUD_DIV = 434    -> 115200
 *      rtl/w3c/evt_uart_rx.v:72 BAUD     = 115200
 *    ⇒ 所以这里【做成可配置】，两边必须一致（一边改了另一边没改 = 完全收不到）。
 *
 * ⚠️ 回环自测时【两个值都要跑】（见总体架构文档 §6.2 判据 6）。
 */
#define BRIDGE_BAUD          1000000
/* #define BRIDGE_BAUD       115200 */

/* ---------------------------------------------------------------------------
 * 3. 引脚
 * ---------------------------------------------------------------------------
 * ⚠️ 必须【交叉接】：
 *      ESP32 的 TX（GPIO17） -> FPGA 的 UART2_RX（G22）
 *      ESP32 的 RX（GPIO18） <- FPGA 的 UART2_TX（G21）
 *
 * 🔴 GPIO43/GPIO44 是 U0（日志）口，⛔ 不要占用。
 * ⚠️ 若模组带 PSRAM（如 ESP32-WROVER），GPIO16/17 可能被 PSRAM 占用 ——
 *    改引脚前先确认模组型号。
 */
#define BRIDGE_UART_PORT     UART_NUM_2
#define BRIDGE_PIN_UART_TX   17
#define BRIDGE_PIN_UART_RX   18

/* 日志口（UART0）保持默认引脚，用于看状态打印 */
#define BRIDGE_LOG_UART_PORT UART_NUM_0
#define BRIDGE_PIN_LOG_TX    1
#define BRIDGE_PIN_LOG_RX    3

/* ===========================================================================
 * 3b. ⭐ 串口屏（TJC T1，走 UART1）
 * ===========================================================================
 *  ⭐ 用途：实时显示"传输进度 / 曲谱名 / 状态 / 蓝牙连接"。
 *
 *  🔴 关键前提：**屏与 FPGA 走【两条完全独立的 UART】**
 *      · UART2 -> FPGA（1 Mbps，⭐ 不受屏影响）
 *      · UART1 -> 屏（115200，⭐ 见下方为什么不用更高）
 *    ⇒ ⭐ 屏的存在【不会】干扰给 FPGA 的数据流。
 *
 *  ⚠️ 为什么屏用 115200 而不是 921600：
 *      屏的**串口缓存只有 1 KB**（官方规格表），而我们只发状态更新
 *      （每秒几百字节）⇒ ⚠️ 高波特率只增加出错概率，⛔ 没有收益。
 *
 *  ⚠️ 电平：⭐ 官方网页文档【没写】T1 的串口电平（规格书是 PDF）。
 *      行业惯例是 3.3 V TTL，但 ⛔ **我没查证到原文，不许当事实用**。
 *      ⇒ 🔴 **上电前必须用万用表量屏 TX 的空闲电平**；
 *         若真是 5 V，⛔ **必须加电平转换**，否则烧 ESP32。
 *
 *  ⚠️ 供电：屏要 **4.65~6.5 V** ⇒ 🔴 **必须给 5 V**（⛔ 不能接 3.3 V）。
 *
 *  ⚠️ 引脚冲突：若模组带 PSRAM，**GPIO16/17 可能被占用** ⇒ 改这里前先确认型号。
 *      ⭐ 这里选 GPIO25/26（经典版 ESP32 的 DAC 脚，空闲、无特殊上电状态）。
 */
/* ⭐ 默认开关值（⚠️ 用 #ifndef 包住，好让 `idf.py -DBRIDGE_HMI_ENABLE=0` 能覆盖它） */
#ifndef BRIDGE_HMI_ENABLE
#define BRIDGE_HMI_ENABLE       1          /* ⭐ 0 = 不接屏（编译期关掉） */
#endif

#define BRIDGE_HMI_UART_PORT    UART_NUM_1
#define BRIDGE_HMI_BAUD         115200     /* ⚠️ 必须与屏内 bauds 设置一致 */
#define BRIDGE_PIN_HMI_TX       25         /* ESP32 TX -> 屏 RX */
#define BRIDGE_PIN_HMI_RX       26         /* ESP32 RX <- 屏 TX */

/* 屏的上电时序（⭐ 官方 QA24 / QA25 明确要求） */
#define BRIDGE_HMI_BOOT_DELAY_MS   300     /* 屏启动需要时间；等它起来再发 */
#define BRIDGE_HMI_BOOT_SYNC       1       /* 发 0x00 FF FF FF 清屏缓冲 */
#define BRIDGE_HMI_WAIT_BOOT_ACK   1       /* ⭐ 等屏回 0x88（比死等 250ms 可靠） */
#define BRIDGE_HMI_BOOT_ACK_MS     2000    /* 等 0x88 的超时（超时就继续，不死等） */

/* 状态刷新周期（ms）—— ⚠️ 太小会刷屏卡顿（屏主控只有 64 MHz） */
#define BRIDGE_HMI_REFRESH_MS      200

/* 单条命令的最大长度（⚠️ 屏串口缓存 1 KB，单条远小于它） */
#define BRIDGE_HMI_CMD_MAX         96

/* ---------------------------------------------------------------------------
 * 4. UART 缓冲
 * ---------------------------------------------------------------------------
 * TX 缓冲要大：帧被拆散后 FPGA 侧表现为"默默少几个音"，
 * 而 resync_cnt / hdr_err_cnt 不一定涨 —— 属于最难查的一类故障。
 *
 * ⚠️ 取 9 的整数倍（1026 = 9*114），使块边界天然落在帧边界上。
 */
#define BRIDGE_UART_TX_BUF   (FRAME_BYTES * 114)   /* 1026 B */
#define BRIDGE_UART_RX_BUF   (FRAME_BYTES * 114)   /* 1026 B */

/* ---------------------------------------------------------------------------
 * 5. 反向通路（UART -> 蓝牙）
 * ---------------------------------------------------------------------------
 * ⚠️ 本轮不是重点（FPGA 侧还没有 uart_tx.v），但先接上，
 *    以满足回环自测判据 5「反向也通」。
 *
 * SPP 官方建议：看到 ESP_SPP_WRITE_EVT 且 cong==false 再发下一包。
 * 这里用保守的固定分块 + 短间隔，够本项目的低速反向用。
 */
#define BRIDGE_BT_TX_CHUNK     256
#define BRIDGE_BT_TX_GAP_MS    2

/* ---------------------------------------------------------------------------
 * 6. 蓝牙设备名
 * ---------------------------------------------------------------------------
 * ⚠️ 手机/PC 靠这个名字找设备。⛔ 不要写含人名的字符串。
 */
#define BRIDGE_BT_NAME        "FPGA2026-Synth"

/* ---------------------------------------------------------------------------
 * 7. 任务优先级与状态打印周期
 * ---------------------------------------------------------------------------
 * ⚠️ 优先级不是越高越好：太高会挤掉蓝牙协议栈任务，反而增大调度抖动。
 */
#define BRIDGE_TASK_PRIO_DRAIN     9
#define BRIDGE_TASK_PRIO_UART_RX   8
#define BRIDGE_TASK_PRIO_STATUS    4
#define BRIDGE_STATUS_PERIOD_MS    1000

/* ===========================================================================
 * 8. ⭐ 转发模式（⭐ 用户拍板：先 A，跑通后再上 B）
 * ===========================================================================
 *   模式 A：纯透传     —— PC 限速，ESP32 收到就转（9N 对齐）
 *   模式 B：二级水池   —— ESP32 缓存整曲 + 自己按谱子时间放水
 *
 * ⚠️ 两模式共用同一套 9N 对齐与写 UART 路径。
 * 🔴 模式 B 需要读事件的 tick/kind（见 pool.c）—— 这是它的代价之一。
 */
#define BRIDGE_MODE_A_PASSTHROUGH   0
#define BRIDGE_MODE_B_POOL          1

/*
 * ⭐ 默认模式。
 *
 * ⚠️ 用 `#ifndef` 包一层，是为了支持【编译期覆盖】：
 *      idf.py -DBRIDGE_MODE=1 build        # 临时编模式 B，⛔ 不用改文件
 *   ⭐ 这样做的好处：**改文件一次只能编一种模式，而且容易忘记改回来**
 *     （⭐ 本文件就因此被 PowerShell 的读写管道毁过一次中文注释）。
 */
#ifndef BRIDGE_MODE
#define BRIDGE_MODE                 BRIDGE_MODE_A_PASSTHROUGH
#endif
/* 想在源码里固定成模式 B，就改上一行的宏（⛔ 不要动上面的 #ifndef/#endif）*/

/* ---------------------------------------------------------------------------
 * 9. ⚠️ 水池参数（⭐ 无条件定义 —— ⛔ 不要放回 #if 里面）
 * ---------------------------------------------------------------------------
 * 🔴 这里踩过一个【真 bug】（⭐ 由首次 `idf.py build` 抓到）：
 *    原来这些宏放在 `#if BRIDGE_MODE == BRIDGE_MODE_B_POOL` 里面，
 *    ⚠️ 而 `pool.c` 是【无条件编译】的（它要引用这些宏）
 *    ⇒ 模式 A 下这些宏【根本没定义】⇒ 🔴 `pool.c` 直接编不过：
 *        error: 'BRIDGE_POOL_BYTES' undeclared here (not in a function)
 *    ⭐ 教训：**"两种模式共用一份工程"不能靠条件编译挡住
 *      【被无条件编译的文件】所需的宏** ⇒ 参数一律无条件定义。
 *
 * 🔴 另记一条【我自己踩的坑】（⭐ 2026-09-23，值得引以为戒）：
 *    为了"临时切模式做编译验证"，我用 PowerShell 做了
 *        (Get-Content f -Raw) -replace ... | Set-Content -Encoding UTF8 f
 *    ⚠️ 结果把本文件【28 行中文注释全毁了】（`馃敶` 这类乱码）——
 *    🔴 因为 `Get-Content` 按 GBK 读 UTF-8 文件，再写回就是"乱码转 UTF-8"。
 *    ⭐ 代码没坏（`#define` 都是 ASCII ⇒ `idf.py build` 照样通过），
 *      ⚠️ **只有注释坏了 ⇒ 编译不报错、极难发现**。
 *    ⇒ ⭐ 纪律：**改这类含中文的文件只用编辑工具，⛔ 不要走 PowerShell 读写管道**。
 *      （同族教训见经验库 C17 / U61）
 */

/*
 * 水池【期望】容量。
 *
 * ⚠️ 这是"想要多少"，⛔ 不是"一定能拿到多少"。
 *    实际拿到多少由 `pool.c` 的 `pool_alloc()` 决定（⭐ 优先 PSRAM，退化内部 DRAM），
 *    ⭐ 运行时用 `pool_stats_t` 的 `capacity_bytes` / `in_psram` 查询。
 *
 * 实测数字（ESP32 经典版，BR/EDR-only，模式 A 基线）：
 *    DRAM 可用总量  = 124,580 B
 *    模式 A 已用    =  44,900 B
 *    剩余           =  79,680 B (77.8 KB)
 *    整曲需求        = 106,785 B (104.3 KB; 09_Conjurer 11,865 事件 × 9 B)
 *    ⇒ 🔴 内部 DRAM 【装不下整曲】⇒ 必须靠 PSRAM
 */
#define BRIDGE_POOL_BYTES           (128 * 1024)

/*
 * ⭐ 提前量（tick）—— 决定"断链容忍"和"FPGA 缓冲占用"的平衡。
 *
 *   FPGA 缓冲 8 KB = 1024 事件。最密曲 夜洋风景 = 99.3 事件/小节，PPQN=960
 *   => 1 小节 = 3840 tick => 每 tick ≈ 0.0259 事件
 *   => 1024 事件 ≈ 39,600 tick
 *
 *   ⇒ ⭐ 取 20,000 tick（≈ 5.2 小节，≈ 517 事件 ≈ 4.1 KB）—— 占 FPGA 缓冲约一半，
 *     留一半余量给"突发和弦"和时钟漂移。
 *
 *   🔴 取太大 ⇒ FPGA 缓冲溢出（静默丢事件）
 *   ⚠️ 取太小 ⇒ 蓝牙一卡就 underrun（掉音）
 */
#define BRIDGE_POOL_LEAD_TICKS      20000u

/*
 * 默认 tick_inc（120 BPM @ PPQN=960, 50 MHz）：
 *   round(2^32 * (120/60) * 960 / 50e6) = 164927
 * ⭐ 与 top.v 的 TICK_INC_120BPM 及 tb_beat_gen.sv 的常量一致。
 * ⚠️ 曲子里若有 kind=2 换速事件，会被就地改写。
 */
#define BRIDGE_POOL_DEFAULT_TICK_INC  164927u

/*
 * ⭐⭐⭐ 放水限流（🔴 2026-09-23 重做 —— 原来是"限帧数"，那是错的）
 * ---------------------------------------------------------------------------
 * 🔴 旧做法问题：`64 帧 / 2 ms` ⇒ 理论 32,000 帧/s（⚠️ FPGA 只消费 ~69.5/s）
 *    且 `vTaskDelay(2ms)` 只是"至少 2ms" ⇒ 被延迟后 due_tick 累积 ⇒ 突发。
 *
 * ⭐ 新做法：**按【tick】限流，⛔ 不按帧数**（⭐ 与 BLE 版同取值同理由）。
 *    1 tick = 520.83 us ⇒ pump 2 ms 正常只推进 3.8 tick
 *    ⇒ 取约 8 倍余量 = **31 tick**（= 提前量的 0.15%）
 * ⚠️ 落后【不追赶】—— 宁可 underrun（可见），⛔ 不要溢出（静默丢）。
 */
#define BRIDGE_POOL_MAX_TICK_ADVANCE     31u

/*
 * ⚠️ 帧数硬上限 —— 防病态情况（某 tick 内海量事件，tick 限流管不住帧数）
 * ⚠️ 取值：FPGA 缓冲 1024 事件 ⇒ 单轮最多 512（一半），连发两轮也不会灌满。
 */
#define BRIDGE_POOL_MAX_FRAMES_PER_PUMP  512u

/* pump 周期（ms）—— 越小越平滑，但任务开销越大 */
#define BRIDGE_POOL_PUMP_PERIOD_MS       2

#endif /* BRIDGE_CONFIG_H */
